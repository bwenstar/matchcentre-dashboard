"""Reading a scorecard, and refusing to read one that cannot be trusted.

Every card here is generated by :mod:`matchcentre.cardwriter` and read back by
:mod:`matchcentre.scorecard`, so the suite needs no PDFs of its own. That matters
twice over: a club's real scorecards carry real players' names and must never be
committed, and a *deliberately damaged* card is the only way to test the behaviour
this project exists for.

The damaged cards are the point. The predecessor read scorecards with a column grid
recovered from the page, and when that recovery failed it fell back to hardcoded
pixel positions. On a page whose content sat 25--60pt from where those constants
expected it, the fallback did not fail — it read the away column as the home column
and reported ``6-2`` as ``2-6``, with every internal check passing. A tool that
guesses wrong silently is worse than one that stops, so each anti-fixture below
asserts a *refusal*, and each names the failure it stands for.
"""

from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from matchcentre import cardwriter as cw, pdf, scorecard        # noqa: E402
from matchcentre import format as fmt_mod                       # noqa: E402
from matchcentre.card import CardError                          # noqa: E402
from matchcentre.model import SetStatus                         # noqa: E402


HOME_PLAYERS = ("Alpha Ashford", "Bravo Beeching", "Charlie Cotterill")
AWAY_PLAYERS = ("Delta Dunmore", "Echo Elmsworth", "Foxtrot Fenwick")


def rows(*scores, doubles=None, status=None, status_side="home"):
    """Set rows from ``(home, away)`` pairs, doubles pattern optional.

    Default pattern is doubles at the ends and singles in between, which is the
    commonest club shape -- but it is always *printed on the card*, never assumed
    by the reader, which is the property these fixtures exist to prove.

    The marker column is deliberately left for ``cardwriter`` to compute. It
    numbers players by first appearance exactly as the real template does, and
    hand-writing markers here would test the fixture rather than the parser.
    """
    if doubles is None:
        doubles = [i in (0, len(scores) - 1) for i in range(len(scores))]
    built = []
    singles_seen = 0
    for index, (home, away) in enumerate(scores):
        pair = doubles[index]
        if pair:
            home_names, away_names = HOME_PLAYERS[:2], AWAY_PLAYERS[:2]
        else:
            # Successive singles rows go to successive players, so the marker
            # column reads 1 then 2 as it does on a real card.
            which = singles_seen % len(HOME_PLAYERS)
            home_names = (HOME_PLAYERS[which],)
            away_names = (AWAY_PLAYERS[which],)
            singles_seen += 1
        built.append(cw.SetRow(
            home_games=home, away_games=away, doubles=pair,
            home_players=home_names, away_players=away_names,
            status=(status if status is not None and index == 0
                    else SetStatus.PLAYED),
            status_side=status_side))
    return tuple(built)


class CardCase(unittest.TestCase):
    """Writes cards into one temporary directory shared by the whole class."""

    @classmethod
    def setUpClass(cls):
        cls._tmp = tempfile.TemporaryDirectory()
        cls.tmp = Path(cls._tmp.name)
        cls._counter = 0

    @classmethod
    def tearDownClass(cls):
        cls._tmp.cleanup()

    def write(self, spec: cw.CardSpec) -> Path:
        type(self)._counter += 1
        path = self.tmp / f"card-{type(self)._counter:03d}.pdf"
        return cw.write_card_file(path, spec)

    def read(self, spec: cw.CardSpec):
        """Parse a spec, raising :class:`CardError` if the page is refused."""
        path = self.write(spec)
        return scorecard.read_page(pdf.extract(path))

    def assert_refused(self, spec: cw.CardSpec, because: str):
        """The card must be refused, and the reason must be actionable.

        Checked both ways round, because they are different promises:
        ``read_page`` raises so a caller cannot ignore it, and ``read`` converts
        that into a counted :class:`~matchcentre.card.Rejection` so a whole run
        reports the bad card by path instead of dying on it.
        """
        path = self.write(spec)
        with self.assertRaises(CardError, msg=f"card was accepted: {because}") as caught:
            scorecard.read_page(pdf.extract(path))
        self.assertTrue(str(caught.exception).strip(),
                        "a refusal with no reason is not actionable")

        cards, rejected = scorecard.read(path)
        self.assertEqual(cards, [], f"{because}: read() returned a card anyway")
        self.assertEqual(len(rejected), 1)
        self.assertIn(str(path), rejected[0].path)
        self.assertTrue(rejected[0].reason.strip())


class TestAnOrdinaryCardIsReadCorrectly(CardCase):

    def test_the_header_is_transcribed_from_the_card_not_from_the_filename(self):
        # Routing on filenames was how the predecessor put a Monday card into a
        # Tuesday ladder. The card's own header is the only source.
        card = self.read(cw.CardSpec(date="2026-08-18", division="C",
                                     round_label="3", court="07",
                                     match_id="1000042"))
        self.assertEqual(card.date, "2026-08-18")
        self.assertEqual(card.weekday, "Tuesday")
        self.assertEqual(card.division, "C")
        self.assertEqual(card.round, "3")
        self.assertEqual(card.court, 7)
        self.assertEqual(card.match_id, "1000042")

    def test_team_names_are_kept_exactly_as_printed(self):
        card = self.read(cw.CardSpec(home_name="RIVERSIDE ROCKETS",
                                     away_name="HILLTOP RTC"))
        self.assertEqual(card.home_name, "RIVERSIDE ROCKETS")
        self.assertEqual(card.away_name, "HILLTOP RTC")

    def test_the_games_land_on_the_right_side(self):
        # The predecessor's measured failure in one line: a reversed scoreline.
        # Deliberately asymmetric per row so a swap cannot pass by symmetry.
        card = self.read(cw.CardSpec(rows=rows((6, 2), (3, 6), (6, 4), (1, 6))))
        self.assertEqual([(s.home_games, s.away_games) for s in card.sets],
                         [(6, 2), (3, 6), (6, 4), (1, 6)])
        self.assertEqual(card.home_games, 16)
        self.assertEqual(card.away_games, 18)

    def test_a_losing_home_side_reads_as_losing(self):
        card = self.read(cw.CardSpec(rows=rows((2, 6), (1, 6), (0, 6), (3, 6))))
        self.assertLess(card.home_games, card.away_games)

    def test_the_printed_totals_are_read_and_agree_with_the_sets(self):
        card = self.read(cw.CardSpec(rows=rows((6, 2), (6, 3), (6, 0), (6, 1))))
        self.assertTrue(card.totals.present)
        self.assertEqual(card.totals.home_games, card.home_games)
        self.assertEqual(card.totals.away_games, card.away_games)
        self.assertTrue(card.confirmed)
        self.assertEqual(card.cross_checks_failed, ())

    def test_the_roster_keeps_ratings_and_marks_the_captain(self):
        spec = cw.CardSpec(home_roster=(
            cw.RosterRow(name="Ana Fernandez", singles=3.82, doubles=3.97),
            cw.RosterRow(name="Bo Nakamura", singles=1.82, doubles=1.82,
                         captain=True),
        ))
        card = self.read(spec)
        names = [e.name for e in card.home_roster]
        self.assertIn("Ana Fernandez", names)
        captain = [e for e in card.home_roster if e.is_captain]
        self.assertEqual([e.name for e in captain], ["Bo Nakamura"])
        ana = next(e for e in card.home_roster if e.name == "Ana Fernandez")
        self.assertAlmostEqual(ana.singles, 3.82, places=2)
        self.assertAlmostEqual(ana.doubles, 3.97, places=2)


class TestTheCourtIsReadWhateverTheVenueIsCalled(CardCase):
    """The venue is printed in the same cell as the court, and it is a club string.

    The predecessor found the court by looking for the literal word
    ``University`` and taking the next token, so every card from every other club
    read as court ``None``. The reader here anchors on the ``Court`` label
    instead -- and that is a claim about clubs this project has never seen, so it
    is worth more than a docstring.
    """

    VENUES = ("Example Courts",        # the shipped default: two words
              "University",            # the one name the predecessor knew
              "Kooyong",               # one word, nothing like the default
              "Centre Court Reserve",  # contains the label's own word
              "Meadowbank Reserve No 2 Courts",   # long, and ends in a number
              "")                      # a club that prints no venue at all

    def test_every_venue_gives_the_court_that_was_printed(self):
        for venue in self.VENUES:
            with self.subTest(venue=venue or "(none)"):
                card = self.read(cw.CardSpec(venue=venue, court="07"))
                self.assertEqual(card.court, 7)

    def test_no_venue_makes_the_card_complain_about_the_court(self):
        # A warning is how a club finds out something was not read. One that
        # fires on an ordinary card teaches them to ignore all of them.
        for venue in self.VENUES:
            with self.subTest(venue=venue or "(none)"):
                card = self.read(cw.CardSpec(venue=venue, court="07"))
                about_court = [w for w in card.warnings if "court" in w.lower()]
                self.assertEqual(about_court, [])

    def test_a_two_digit_court_is_not_confused_with_a_number_in_the_venue(self):
        card = self.read(cw.CardSpec(venue="Meadowbank Reserve No 2 Courts",
                                     court="11"))
        self.assertEqual(card.court, 11)


class TestTheFormatIsReadOffTheCard(CardCase):

    def test_a_three_set_card_yields_three_sets(self):
        # Not four. The predecessor assumed four everywhere, so a three-set
        # competition lost a rubber and a five-set one gained a phantom.
        card = self.read(cw.CardSpec(rows=rows((6, 1), (6, 2), (6, 3))))
        self.assertEqual(len(card.sets), 3)

    def test_a_five_set_card_yields_five_sets(self):
        card = self.read(cw.CardSpec(
            rows=rows((6, 1), (6, 2), (6, 3), (6, 4), (6, 0))))
        self.assertEqual(len(card.sets), 5)

    def test_each_row_reports_its_own_discipline_from_its_own_marker(self):
        card = self.read(cw.CardSpec(
            rows=rows((6, 1), (6, 2), (6, 3), (6, 4),
                      doubles=[True, False, False, True])))
        self.assertEqual(card.doubles_flags, (True, False, False, True))

    def test_an_all_singles_card_is_read_as_all_singles(self):
        card = self.read(cw.CardSpec(
            rows=rows((6, 1), (6, 2), (6, 3), doubles=[False, False, False])))
        self.assertEqual(card.doubles_flags, (False, False, False))

    def test_a_doubles_row_names_two_players_a_side(self):
        card = self.read(cw.CardSpec(rows=rows((6, 1), (6, 2))))
        first = card.sets[0]
        self.assertEqual(len(first.home_players), 2)
        self.assertEqual(len(first.away_players), 2)

    def test_the_format_the_card_describes_matches_what_it_printed(self):
        card = self.read(cw.CardSpec(
            rows=rows((6, 1), (6, 2), (6, 3), doubles=[True, False, True])))
        shape = fmt_mod.from_rows(card.doubles_flags)
        self.assertEqual(len(shape.slots), 3)
        self.assertEqual([s.doubles for s in shape.slots], [True, False, True])


class TestSetStatusComesFromTheTickedBox(CardCase):

    def test_a_retired_set_is_marked_retired(self):
        card = self.read(cw.CardSpec(
            rows=rows((4, 2), (6, 1), (6, 0), (6, 3),
                      status=SetStatus.RETIRED)))
        self.assertEqual(card.sets[0].status, SetStatus.RETIRED)

    def test_a_forfeited_set_records_which_side_forfeited(self):
        card = self.read(cw.CardSpec(
            rows=rows((6, 0), (6, 1), (6, 2), (6, 3),
                      status=SetStatus.FORFEIT, status_side="away")))
        self.assertEqual(card.sets[0].status, SetStatus.FORFEIT)
        self.assertTrue(card.sets[0].away_forfeit)
        self.assertFalse(card.sets[0].home_forfeit)

    def test_an_untouched_card_has_no_status_marks_at_all(self):
        card = self.read(cw.CardSpec())
        self.assertEqual({s.status for s in card.sets}, {SetStatus.PLAYED})
        self.assertFalse(any(s.home_forfeit or s.away_forfeit
                             for s in card.sets))

    def test_a_match_forfeit_ticked_on_both_sides_names_neither(self):
        # Measured on the predecessor: it paid the forfeit-win value to BOTH
        # sides, because nothing checked that exactly one forfeiter was named.
        # The card must report the ambiguity rather than resolve it, so either a
        # refusal or `forfeited_by is None` is correct -- silently picking a side
        # is not.
        spec = cw.CardSpec(rows=rows((0, 0), (0, 0), (0, 0), (0, 0)),
                           forfeited_by="both", winner=cw.NO_TICK,
                           omit_totals=True, omit_verb=True)
        path = self.write(spec)
        try:
            card = scorecard.read_page(pdf.extract(path))
        except CardError:
            return
        self.assertIsNone(card.forfeited_by,
                          "both Match Forfeited boxes are ticked and the card "
                          "still named a forfeiter")

    def test_a_cancelled_card_is_marked_cancelled(self):
        card = self.read(cw.CardSpec(rows=rows((0, 0), (0, 0), (0, 0), (0, 0)),
                                     cancelled=True, winner=cw.NO_TICK,
                                     omit_totals=True, omit_verb=True))
        self.assertTrue(card.cancelled)


PLACEHOLDER = "Unspecified player"


class TestTheSitesPlaceholderForNobodyIsNotAPlayer(CardCase):
    """``Unspecified player``: what Match Centre prints in a name cell nobody filled.

    Measured on a real export. A washed-out round's card had been created and never
    filled in, so all twelve of its name cells printed the placeholder -- and the
    placeholder was read as a person. That invented a player: one squad of one, on
    no team, whose only opponent was itself, with more rubbers to its name than
    anybody real, listed on the dashboard among the players worth checking. The
    validator said nothing, because a cancelled card is exempt from the roster
    checks that would have caught it.

    It is the template's own empty state, so it is dropped -- and *counted*, because
    a card quietly thinned out is the other half of the same failure.
    """

    def blank_rows(self, *scores):
        """Set rows in the shape of a card whose players were never entered."""
        return tuple(cw.SetRow(home_games=home, away_games=away,
                               doubles=index in (0, len(scores) - 1),
                               home_players=(PLACEHOLDER,) * (
                                   2 if index in (0, len(scores) - 1) else 1),
                               away_players=(PLACEHOLDER,) * (
                                   2 if index in (0, len(scores) - 1) else 1))
                     for index, (home, away) in enumerate(scores))

    def test_the_placeholder_is_recognised_however_it_is_punctuated(self):
        # Casing and trailing punctuation vary between exports; the plural does
        # too, on a doubles row.
        for text in ("Unspecified player", "unspecified players", "UNSPECIFIED "
                     "PLAYER", " Unspecified  player ", "Unspecified."):
            with self.subTest(text=text):
                self.assertTrue(scorecard.names_nobody(text))

    def test_a_real_name_is_not_mistaken_for_it(self):
        # The predicate is exact, not a substring test: a club can have a member
        # whose name contains any of these words.
        for text in HOME_PLAYERS + ("Player One", "Spec Unspecified-Jones"):
            with self.subTest(text=text):
                self.assertFalse(scorecard.names_nobody(text))

    def test_no_name_is_read_from_a_cell_that_names_nobody(self):
        card = self.read(cw.CardSpec(rows=self.blank_rows((0, 0), (0, 0),
                                                          (0, 0), (0, 0)),
                                     cancelled=True, winner=cw.NO_TICK,
                                     omit_totals=True, omit_verb=True))
        for parsed in card.sets:
            with self.subTest(row=parsed.index):
                self.assertEqual(parsed.home_players, ())
                self.assertEqual(parsed.away_players, ())

    def test_how_many_cells_named_nobody_is_kept_rather_than_forgotten(self):
        # The count is what lets one warning per card say how much of it was never
        # filled in. Dropped silently, a card that needs re-exporting looks clean.
        card = self.read(cw.CardSpec(rows=self.blank_rows((0, 0), (0, 0),
                                                          (0, 0), (0, 0)),
                                     cancelled=True, winner=cw.NO_TICK,
                                     omit_totals=True, omit_verb=True))
        self.assertEqual([s.unnamed for s in card.sets], [4, 2, 2, 4])

    def test_a_card_with_real_names_counts_none(self):
        # Without this the count above could be anything at all and still pass.
        card = self.read(cw.CardSpec(rows=rows((6, 1), (6, 2), (6, 3), (6, 4))))
        self.assertEqual([s.unnamed for s in card.sets], [0, 0, 0, 0])

    def test_the_games_on_such_a_row_are_still_read(self):
        # A row can print games and no names -- a card filled in from the scoresheet
        # in a hurry. The scoreline is evidence and is kept; inventing a player to
        # attach it to is not the way to keep it.
        card = self.read(cw.CardSpec(rows=self.blank_rows((6, 1), (6, 2),
                                                          (3, 6), (6, 4))))
        self.assertEqual([(s.home_games, s.away_games) for s in card.sets],
                         [(6, 1), (6, 2), (3, 6), (6, 4)])
        self.assertEqual(card.home_games, 21)

    def test_a_roster_line_naming_nobody_registers_nobody(self):
        # Worse than the same placeholder in a set row: this one would put the
        # phantom on a team, and a team's squad list is what closes the roster
        # checks.
        card = self.read(cw.CardSpec(
            rows=rows((6, 1), (6, 2), (6, 3), (6, 4)),
            home_roster=(cw.RosterRow(name=PLACEHOLDER, singles=2.5, doubles=2.5),
                         cw.RosterRow(name=HOME_PLAYERS[0], singles=2.5,
                                      doubles=2.5, captain=True))))
        self.assertEqual([e.name for e in card.home_roster], [HOME_PLAYERS[0]])

    def test_describing_the_card_says_which_rows_lost_their_names(self):
        # `describe` is what a club is told to paste when asking for help, so the
        # thing that was dropped has to be in it.
        path = self.write(cw.CardSpec(rows=self.blank_rows((0, 0), (0, 0),
                                                           (0, 0), (0, 0)),
                                      cancelled=True, winner=cw.NO_TICK,
                                      omit_totals=True, omit_verb=True))
        described = scorecard.describe(pdf.extract(path))
        self.assertIn("placeholder", described)
        self.assertIn("no player", described)


class TestADamagedCardIsRefused(CardCase):
    """F5: fail closed. Each of these produced a wrong number in the predecessor."""

    def test_a_shifted_page_is_refused_rather_than_guessed(self):
        # THE measured failure. A 40pt offset defeated the predecessor's column
        # recovery, its pixel-constant fallback took over, and it reported the
        # scoreline reversed. Nothing in its output said anything was wrong.
        self.assert_refused(cw.CardSpec(page_offset=40.0),
                            "a 40pt page offset defeats column recovery")

    def test_a_missing_column_rule_is_refused(self):
        # The column rules are how home is told from away. With one gone the
        # grid is ambiguous, and an ambiguous grid is exactly where a reversed
        # scoreline comes from.
        self.assert_refused(cw.CardSpec(drop_column_rule=3),
                            "a column rule is missing")

    def test_a_file_that_is_not_a_pdf_becomes_a_rejection_not_a_crash(self):
        stray = self.tmp / "not-a-card.pdf"
        stray.write_bytes(b"This is a text file with a misleading extension.\n")
        cards, rejected = scorecard.read(stray)
        self.assertEqual(cards, [])
        self.assertEqual(len(rejected), 1)
        self.assertTrue(rejected[0].reason.strip())

    def test_an_empty_file_becomes_a_rejection(self):
        empty = self.tmp / "empty.pdf"
        empty.write_bytes(b"")
        cards, rejected = scorecard.read(empty)
        self.assertEqual(cards, [])
        self.assertEqual(len(rejected), 1)


class TestAFontWithNoToUnicodeMapIsStillRead(CardCase):
    """A predecessor failure that is *fixed* here, not refused.

    Its reader honoured only the ``/ToUnicode`` CMap, so a font without one
    yielded ``""`` for every glyph and the card came out blank -- and a blank card
    is indistinguishable downstream from a card that had nothing on it. ``pdf.py``
    falls back to ``/Encoding``, its ``/Differences``, the named base encodings and
    finally Latin-1, so the text is decoded rather than lost. Refusing such a card
    would throw away one that is perfectly readable.
    """

    def test_the_text_is_decoded_from_the_encoding_instead(self):
        card = self.read(cw.CardSpec(omit_to_unicode=True))
        self.assertEqual(card.home_name, "EXAMPLE ALPHAS")
        self.assertEqual(len(card.sets), 4)

    def test_it_reads_identically_to_the_same_card_with_a_cmap(self):
        # The strongest form of the claim: the CMap is redundant, not merely
        # survivable. Source and page number differ by construction, so the
        # comparison is over everything else the card says.
        plain = self.read(cw.CardSpec())
        without = self.read(cw.CardSpec(omit_to_unicode=True))
        for field in ("home_name", "away_name", "date", "division", "round",
                      "court", "match_id", "verb", "sets", "home_roster",
                      "away_roster", "totals", "winner_tick"):
            with self.subTest(field=field):
                self.assertEqual(getattr(plain, field), getattr(without, field))


class TestAContradictoryTickIsReportedNotResolved(CardCase):
    """F6: a cross-check that disagrees is an *error*, not a refusal.

    Worth being precise about, because the two are easy to conflate. The card's
    scores are intact and independently confirmed by the printed ``TOTAL`` row and
    the result verb; only the redundant winner tick contradicts them. Refusing the
    whole card would discard good data over a failed confirmation. What must never
    happen is the parser *picking* a winner -- that is how a lost match becomes a
    won one -- so it reports both readings and lets ``validate.py`` raise the error.
    """

    def spec(self) -> cw.CardSpec:
        return cw.CardSpec(extra_tick=True)

    def test_neither_side_is_named_the_winner(self):
        self.assertIsNone(self.read(self.spec()).winner_tick)

    def test_the_disagreement_is_recorded_as_a_failed_cross_check(self):
        card = self.read(self.spec())
        failed = [c.name for c in card.cross_checks_failed]
        self.assertIn("winner-tick", failed)

    def test_the_card_is_not_confirmed(self):
        self.assertFalse(self.read(self.spec()).confirmed)

    def test_a_warning_says_what_is_wrong_in_words_a_human_can_act_on(self):
        card = self.read(self.spec())
        self.assertTrue(card.warnings)
        joined = " ".join(card.warnings).casefold()
        self.assertIn("both", joined)
        self.assertIn("winner", joined)

    def test_the_scores_are_still_read_correctly(self):
        # The point of not refusing: everything the card says unambiguously is
        # still available, and still right.
        card = self.read(cw.CardSpec(extra_tick=True,
                                     rows=rows((6, 2), (3, 6), (6, 4), (1, 6))))
        self.assertEqual([(s.home_games, s.away_games) for s in card.sets],
                         [(6, 2), (3, 6), (6, 4), (1, 6)])


class TestAThinCardIsReadButNotTrusted(CardCase):
    """Missing cross-checks are a template variation, not a fault. Say so."""

    def test_a_card_with_no_totals_row_still_reads(self):
        card = self.read(cw.CardSpec(omit_totals=True))
        self.assertEqual(len(card.sets), 4)
        self.assertFalse(card.totals.present)

    def test_a_card_with_no_result_verb_still_reads(self):
        card = self.read(cw.CardSpec(omit_verb=True))
        self.assertEqual(len(card.sets), 4)
        self.assertEqual(card.verb, "")

    def test_a_card_with_no_cross_check_at_all_is_not_confirmed(self):
        # It is still read, and its numbers are still reported -- but `confirmed`
        # is false, and validate.py turns that into a warning a human sees. The
        # alternative, treating unverifiable numbers as verified, is what makes a
        # dashboard confidently wrong.
        card = self.read(cw.CardSpec(omit_totals=True, omit_verb=True,
                                     winner=cw.NO_TICK))
        self.assertEqual(card.cross_checks_available, ())
        self.assertFalse(card.confirmed)

    def test_a_totals_row_that_disagrees_with_the_sets_fails_its_check(self):
        # The card says one thing twice and the two disagree, so one of them was
        # misread. Refusing is right; reporting whichever came first is not.
        spec = cw.CardSpec(rows=rows((6, 2), (6, 3), (6, 0), (6, 1)),
                           totals=(4, 99, 6, 0))
        path = self.write(spec)
        try:
            card = scorecard.read_page(pdf.extract(path))
        except CardError:
            return          # refusing outright is an acceptable stronger answer
        self.assertTrue(card.cross_checks_failed,
                        "the printed TOTAL disagrees with the sets and nothing "
                        "noticed")
        self.assertFalse(card.confirmed)


class TestVSIsASeparatorNotAnUnknownVerb(CardCase):
    """A card with no result printed on it, told apart from a word we do not know.

    Match Centre prints ``DEFEATS`` or ``DEF. BY`` between the team names when it
    holds a result, and ``VS`` when it does not. Both readings leave the verb
    cross-check unavailable, so it is tempting to report them the same way — but
    they are opposite findings. An unknown word means this reader has a word to
    learn and the card had a result it could not use; a separator means the card
    itself states no result, and there is nothing here to fix. Reported as "not one
    this reader recognises", the second reads as *this card was not understood*,
    and a club's fair conclusion is that the card went uncounted. It did not: the
    sets, the roster and the printed ``TOTAL`` are all still read.
    """

    def spec(self, **kw) -> cw.CardSpec:
        # No Match Winner tick either: on the real cards the two absences were
        # measured together, every time. That leaves the TOTAL row as the only
        # confirmation the card offers, which is what the last test here is about.
        fields = {"verb": "VS", "winner": cw.NO_TICK,
                  "rows": rows((6, 2), (3, 6), (6, 4), (1, 6))}
        return cw.CardSpec(**{**fields, **kw})

    def test_the_separator_is_recognised_in_the_forms_a_card_prints_it(self):
        for verb in ("VS", "vs", "Vs.", " V ", "VERSUS"):
            with self.subTest(verb=verb):
                self.assertTrue(scorecard.states_no_result(verb))

    def test_a_result_verb_is_never_mistaken_for_the_separator(self):
        # The blank is in this list on purpose: a card that printed no verb at all
        # is a third finding, not this one.
        for verb in ("DEFEATS", "DEF. BY", "DRAWS WITH", "TROUNCES", ""):
            with self.subTest(verb=verb):
                self.assertFalse(scorecard.states_no_result(verb))

    def test_every_set_row_is_still_read_off_a_card_printing_vs(self):
        card = self.read(self.spec())
        self.assertEqual([(s.home_games, s.away_games) for s in card.sets],
                         [(6, 2), (3, 6), (6, 4), (1, 6)])

    def test_the_printed_verb_is_passed_through_untouched(self):
        self.assertEqual(self.read(self.spec()).verb, "VS")

    def verb_check(self, spec: cw.CardSpec):
        check, = [c for c in self.read(spec).checks if c.name == "verb"]
        self.assertFalse(check.available)
        return check

    def test_the_verb_check_says_the_card_states_no_result(self):
        detail = self.verb_check(self.spec()).detail
        self.assertIn("VS", detail)
        self.assertIn("states no result", detail)
        self.assertNotIn("recognis", detail,
                         "a separator reported as an unrecognised word is the "
                         "wording that sent a club looking for a lost card")

    def test_a_word_this_reader_does_not_know_still_says_so(self):
        detail = self.verb_check(self.spec(verb="TROUNCES")).detail
        self.assertIn("TROUNCES", detail)
        self.assertIn("recognis", detail)

    def test_a_card_with_no_verb_at_all_says_that_instead_of_either(self):
        detail = self.verb_check(self.spec(omit_verb=True)).detail
        self.assertIn("no result verb", detail)
        self.assertNotIn("recognis", detail)

    def test_the_card_is_still_confirmed_by_its_printed_total_row(self):
        # One confirmation of three, and it is enough: a card confirmed once is not
        # a card in doubt. Losing the other two is why the run says anything at all.
        card = self.read(self.spec())
        self.assertEqual([c.name for c in card.cross_checks_available], ["totals"])
        self.assertTrue(card.confirmed)


class TestTheFixtureCardHasTheShapeOfARealOne(CardCase):
    """Every test in this suite rests on the generated card resembling a real one.

    Each number below was measured off a real exported scorecard and is written
    out here as a literal. None of them is read back out of ``cardwriter``, and
    that is the whole discipline of this class: a test that asks the code what to
    expect agrees with the code however the code is edited. The first draft did
    ask -- it took the inset rules from ``cardwriter.INSET_COLUMN_RULES`` -- and
    emptying that constant, so that every rule was painted the wrong height, left
    this class green. Literals here, geometry there.

    The whole page is claimed, not just the set table: a four-row card carries the
    same 200 rects a real four-row card carries, shape for shape and count for
    count, every one within 0.05pt of where the real producer puts it. That matters
    beyond tidiness. The reader finds the roster from the ``Players`` heading and
    the words under it, and the totals from the numbers in their cells -- so a
    fixture that omitted the boxes around them would exercise the same code today,
    and would quietly stop doing so the day a reader started clustering rects to
    locate either. A fixture that is missing shapes is a fixture that cannot fail
    that way.
    """

    PANEL = (10.29, 10.29, 574.56, 602.22)          # x, y, w, h -- white, painted first
    TABLE_TOP = 126.70                              # the first band starts here
    HEADING_HEIGHT = 39.76
    HEADING_CELLS = ((26.42, 34.58), (61.00, 473.13), (534.13, 34.58))
    # Every vertical rule in the set table, as (x, height). The middle four are
    # 1.16pt shorter than the outer four; four of each is not a coincidence to be
    # relied on, so they are listed rather than counted.
    RULES = ((26.42, 47.26), (61.58, 47.26), (250.60, 46.10), (281.14, 46.10),
             (313.41, 46.10), (343.96, 46.10), (532.98, 47.26), (568.13, 47.26))
    BANDS = 4
    SEPARATOR_ROWS = (173.38, 220.63, 267.89, 315.14)
    SEPARATOR_SEGMENTS = ((26.42, 35.15), (61.58, 471.98), (533.56, 35.15))
    NEAR = 0.1                                      # a tenth of a point

    def rects(self, spec: cw.CardSpec):
        return pdf.extract(self.write(spec)).rects

    def verticals(self, spec: cw.CardSpec | None = None):
        return [r for r in self.rects(spec or cw.CardSpec())
                if r.w < 1 and 40 < r.h < 55]

    def horizontals(self, spec: cw.CardSpec | None = None):
        return [r for r in self.rects(spec or cw.CardSpec())
                if r.h < 1 and r.w > 30]

    def test_the_white_panel_under_everything_is_there_and_is_the_only_one(self):
        # A real producer lays one down; it is by far the largest rect on the page
        # and it is not part of the grid. A reader that took the biggest rect for
        # the table would pass on a fixture that had none.
        big = [r for r in self.rects(cw.CardSpec()) if r.w > 400 and r.h > 400]
        self.assertEqual(len(big), 1, f"expected exactly one page panel, got "
                                      f"{[(round(r.w, 2), round(r.h, 2)) for r in big]}")
        for name, got, want in (("x", big[0].x0, self.PANEL[0]),
                                ("y", big[0].y0, self.PANEL[1]),
                                ("width", big[0].w, self.PANEL[2]),
                                ("height", big[0].h, self.PANEL[3])):
            with self.subTest(panel=name):
                self.assertAlmostEqual(got, want, delta=self.NEAR)

    def test_the_heading_band_is_three_cells_sitting_on_the_table_top(self):
        found = sorted((r for r in self.rects(cw.CardSpec())
                        if abs(r.h - self.HEADING_HEIGHT) < self.NEAR),
                       key=lambda r: r.x0)
        self.assertEqual([(round(r.x0, 2), round(r.w, 2)) for r in found],
                         [(round(x, 2), round(w, 2))
                          for x, w in self.HEADING_CELLS])
        for cell in found:
            # Its underside *is* the top of the table; see the test below on why
            # nothing else may be painted there.
            self.assertAlmostEqual(cell.y1, self.TABLE_TOP, delta=self.NEAR)

    def test_the_grid_has_no_more_verticals_than_a_real_card(self):
        # Thirty-two: eight rules, four bands, once each. Painting each rule twice
        # was the bug, and 64 verticals would make any count assertion about this
        # table wrong while looking, band by band, entirely plausible.
        self.assertEqual(len(self.verticals()), len(self.RULES) * self.BANDS)

    def test_every_rule_stands_where_the_real_card_paints_it_and_as_tall(self):
        found = self.verticals()
        for x, height in self.RULES:
            at_x = [r for r in found if abs(r.x0 - x) < self.NEAR]
            with self.subTest(rule_x=x):
                self.assertEqual(len(at_x), self.BANDS,
                                 f"expected one rule at x={x} per band, got "
                                 f"{len(at_x)}")
                for rect in at_x:
                    self.assertAlmostEqual(rect.h, height, delta=self.NEAR)

    def test_each_band_is_closed_by_three_segments_and_not_one_line(self):
        # Three, with the gaps a real card leaves where the marker columns end.
        # One full-width line would read as the same boundary to a human and let a
        # reader start keying on a line no club's card has.
        found = self.horizontals()
        for y in self.SEPARATOR_ROWS:
            at_y = sorted((r for r in found if abs(r.y0 - y) < self.NEAR),
                          key=lambda r: r.x0)
            with self.subTest(separator_y=y):
                self.assertEqual([(round(r.x0, 2), round(r.w, 2)) for r in at_y],
                                 [(round(x, 2), round(w, 2))
                                  for x, w in self.SEPARATOR_SEGMENTS])

    def test_nothing_is_painted_across_the_top_of_the_table(self):
        # The heading band is the boundary there. A line would be a line no
        # club's card has, and the reader must not learn to expect one.
        across = [r for r in self.horizontals()
                  if abs(r.y0 - self.TABLE_TOP) < self.NEAR * 2]
        self.assertEqual(across, [])

    # Every rect on a real four-row card, as ``(width, height): count``. Twenty-four
    # shapes, two hundred rects, and the writer must account for all of them: the
    # tally is what turns "looks about right" into a number that can be wrong.
    MEASURED_RECTS = {
        (0.58, 8.07): 60, (8.07, 0.58): 60,          # checkbox edges
        (0.58, 46.10): 16, (0.58, 47.26): 16,        # column rules, inset and flush
        (35.15, 0.58): 8, (471.98, 0.58): 4,         # band separators, in segments
        (46.68, 0.58): 6, (47.26, 0.58): 3, (46.10, 0.58): 3,
        (0.58, 11.53): 4, (0.58, 14.98): 4,          # the totals grid
        (32.85, 0.58): 2, (0.58, 26.51): 2,          # and its TOTAL cell
        (34.58, 39.76): 2, (473.13, 39.76): 1,       # the tinted heading band
        (8.07, 8.07): 1,                             # one ticked box: Match Winner
        (72.04, 0.58): 1,                            # the write-on line by "Court:"
        (148.11, 0.58): 1, (153.87, 0.58): 1,        # "Signed by:"
        (141.19, 0.58): 1, (64.54, 0.58): 1,
        (145.22, 0.58): 1, (65.12, 0.58): 1,         # under "Players  Rating"
        (574.56, 602.22): 1,                         # the white panel
    }
    # A home win, so that exactly one Match Winner box is ticked -- as on the card
    # these numbers were taken from.
    HOME_WIN = ((6, 2), (6, 3), (6, 0), (6, 1))

    # The six per-set status boxes on each side, measured. The template does not
    # space them uniformly from their labels, so deriving them from one offset put
    # four of the six a third of a point out.
    STATUS_BOX_X = (67.91, 104.80, 144.56, 403.89, 441.35, 481.11)

    def test_the_status_boxes_stand_where_the_real_card_puts_them(self):
        edges = [r for r in self.rects(cw.CardSpec())
                 if abs(r.h - cw.BOX_SIDE) < self.NEAR and r.w < 1]
        for x in self.STATUS_BOX_X:
            with self.subTest(box_x=x):
                # A left edge in every band, and a right edge one box further on.
                for side, at in (("left", x), ("right", x + cw.BOX_SIDE - cw.HAIRLINE)):
                    found = [r for r in edges if abs(r.x0 - at) < self.NEAR]
                    self.assertEqual(len(found), self.BANDS,
                                     f"expected {self.BANDS} {side} edges at "
                                     f"x={at:.2f}, found {len(found)}")

    def test_the_page_carries_exactly_the_rects_a_real_card_carries(self):
        found: dict[tuple[float, float], int] = {}
        for rect in self.rects(cw.CardSpec(rows=rows(*self.HOME_WIN))):
            shape = (round(rect.w, 2), round(rect.h, 2))
            found[shape] = found.get(shape, 0) + 1
        wanted = {(round(w, 2), round(h, 2)): n
                  for (w, h), n in self.MEASURED_RECTS.items()}
        differences = sorted(f"{shape}: real card {wanted.get(shape, 0)}, "
                             f"this card {found.get(shape, 0)}"
                             for shape in set(wanted) | set(found)
                             if wanted.get(shape, 0) != found.get(shape, 0))
        self.assertEqual(differences, [],
                         f"{len(differences)} shape(s) differ from a real card:\n  "
                         + "\n  ".join(differences))
        self.assertEqual(sum(found.values()), sum(wanted.values()))

    def test_the_totals_row_is_boxed_the_way_the_real_card_boxes_it(self):
        # Three horizontals per cell, not four: the heading row's floor is the value
        # row's ceiling. A box-per-row writer puts four there, which is four rects a
        # club's card does not have and a wrong answer to "how many lines are here".
        found = self.horizontals(cw.CardSpec(rows=rows(*self.HOME_WIN)))
        cell_x = {round(x, 2) for x, _w in cw.TOTALS_GRID_CELLS}
        in_cells = [r for r in found if round(r.x0, 2) in cell_x]
        per_cell: dict[float, int] = {}
        for rect in in_cells:
            per_cell[round(rect.x0, 2)] = per_cell.get(round(rect.x0, 2), 0) + 1
        self.assertEqual(sorted(per_cell.values()), [3] * len(cell_x))

    def test_the_block_below_the_table_moves_down_with_a_longer_table(self):
        # Every rect under the table is placed as an offset from the bottom of the
        # last band. A six-set card has a table two rows taller, and a prototype
        # that placed this block at absolute y ruled its TOTAL row through rows five
        # and six. Compared as offsets from each card's own table bottom, so the two
        # cards must describe the same block however many rows are above it.
        four = self.below_the_table(rows(*self.HOME_WIN))
        six = self.below_the_table(rows(*self.HOME_WIN, (6, 4), (2, 6)))
        self.assertTrue(four, "no rects found below the table at all")
        self.assertEqual(four, six)

    def below_the_table(self, set_rows) -> set:
        """Rects under the last band, as ``(x, w, h, offset)`` from its bottom."""
        spec = cw.CardSpec(rows=set_rows)
        bottom = cw.TABLE_TOP + len(set_rows) * cw.ROW_HEIGHT
        return {(round(r.x0, 2), round(r.w, 2), round(r.h, 2),
                 round(r.y0 - bottom, 2))
                for r in self.rects(spec) if r.y0 > bottom}

    def test_the_reader_still_gets_every_number_off_it(self):
        # The point of all of the above. Structure that matches a real card is
        # only worth having if the card still reads.
        card = self.read(cw.CardSpec(rows=rows((6, 2), (3, 6), (6, 4), (1, 6)),
                                     court="07"))
        self.assertEqual([(s.home_games, s.away_games) for s in card.sets],
                         [(6, 2), (3, 6), (6, 4), (1, 6)])
        self.assertEqual(card.court, 7)
        self.assertTrue(card.confirmed)
        self.assertEqual(list(card.warnings), [])


class TestReadingIsDeterministic(CardCase):

    def test_the_same_spec_writes_the_same_bytes(self):
        # Determinism starts at the fixture. If cardwriter is not deterministic,
        # no test built on it can distinguish a real change from noise.
        spec = cw.CardSpec(rows=rows((6, 2), (6, 3), (6, 0), (6, 1)))
        self.assertEqual(cw.write_card(spec), cw.write_card(spec))

    def test_the_same_card_reads_the_same_twice(self):
        path = self.write(cw.CardSpec())
        first = scorecard.read_page(pdf.extract(path))
        second = scorecard.read_page(pdf.extract(path))
        self.assertEqual(first, second)

    def test_a_tree_of_cards_is_read_in_path_order(self):
        # Order fixes tie-breaks and so fixes output. Directory order does not.
        tree = self.tmp / "tree"
        (tree / "R2").mkdir(parents=True, exist_ok=True)
        (tree / "R1").mkdir(parents=True, exist_ok=True)
        for name, spec in (("R2/b.pdf", cw.CardSpec(round_label="2")),
                           ("R1/a.pdf", cw.CardSpec(round_label="1"))):
            cw.write_card_file(tree / name, spec)
        cards, rejected = scorecard.read_tree(tree)
        self.assertEqual(rejected, [])
        self.assertEqual([c.round for c in cards], ["1", "2"])

    def test_every_pdf_found_is_either_a_card_or_a_rejection(self):
        # F11 in one assertion: nothing may be skipped in silence. A scorecard
        # that vanishes leaves a plausible ladder with a team short a match.
        tree = self.tmp / "mixed"
        tree.mkdir(parents=True, exist_ok=True)
        cw.write_card_file(tree / "good.pdf", cw.CardSpec())
        cw.write_card_file(tree / "shifted.pdf", cw.CardSpec(page_offset=40.0))
        (tree / "junk.pdf").write_bytes(b"not a pdf at all")
        cards, rejected = scorecard.read_tree(tree)
        self.assertEqual(len(cards) + len(rejected), 3)
        self.assertEqual(len(cards), 1)


