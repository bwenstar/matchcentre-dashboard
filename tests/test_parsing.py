    def test_a_file_none_of_whose_pages_can_be_read_gives_the_first_pages_reason(self):
        both = self.with_a_second_page(self.card()[3].replace(b"/Contents 6 0 R", b""))
        both[3] = both[3].replace(b"/Contents 6 0 R", b"")
