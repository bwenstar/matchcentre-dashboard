        for heading in ("Emergencies", "Fill Ins"):
            for dash in self.NO_LETTER:
                with self.subTest(heading=heading, dash=dash):
                    card = self.read(cw.CardSpec(fill_ins_headings=(heading, heading),
                                                 home_fill_ins=(dash,),
                                                 away_fill_ins=(dash,)))
