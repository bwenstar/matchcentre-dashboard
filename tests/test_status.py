"""The front page's one sentence about the last build, and the file it arrives in.

A build that failed left every file under ``site/`` exactly as the last good one
wrote it, and nothing on the page said so. Measured on the demo season before this
file existed: with ``data/`` emptied, renamed away, or holding only a card that
would not read, the run exited 1, 2 and 1, every ``st_mtime_ns`` under ``site/``
was unchanged, and the front page still said "Generated ... 23 Sep, 5:20pm" over
figures nobody could tell were stale.

So a build that worked writes ``build-status.js`` holding nothing but
``{"level": "ok"}``, and a build that failed replaces it with one sentence from a
fixed list of ten -- but only over a file that is already there and already
carries the generated mark. A failed run never creates a site, and never
overwrites a file it cannot prove is its own.

Rejected: a clean sentence with the date and the counts in it. The footer already
dates the figures and every competition card already flags its unreadable cards,
so the page would say both twice; and a status that moved with the card count
would move with every card, which is one more file rewritten on every night the
figures change.
"""

from __future__ import annotations

import json
import os
import re
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from matchcentre import site, status                     # noqa: E402

CLEAN_BYTES = (b"// Generated by build.py -- do not edit.\n"
               b"window.BUILD_STATUS = {\n"
               b'  "level": "ok"\n'
               b"};\n")


class StatusCase(unittest.TestCase):
    """A temp folder standing in for ``--out``."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.base = Path(self._tmp.name)
        self.out = self.base / "site"
        self.addCleanup(self._tmp.cleanup)

    def seed(self, data: bytes = CLEAN_BYTES) -> Path:
        self.out.mkdir(exist_ok=True)
        path = self.out / site.STATUS_FILE
        path.write_bytes(data)
        return path

    def text(self, path: Path) -> str:
        """The sentence a browser would be handed, out of the file as written."""
        body = path.read_text(encoding="utf-8").split("\n", 1)[1]
        found = re.fullmatch(r"window\.BUILD_STATUS = (.*);\n", body, re.S)
        self.assertIsNotNone(found, body)
        return json.loads(found.group(1)).get("text", "")


class TestACleanBuildWritesAStatusThatSaysNothing(unittest.TestCase):
    """A build that worked writes the same bytes every time, and they say nothing.

    The footer already carries the date the figures last changed, so a clean file
    with a date, a count or a sentence in it would be a second place for the page
    to say it -- and a file that changed with the card count would be rewritten on
    every night a card arrived, which 4.12's "a card moves four files" forbids.
    """

    def test_the_clean_file_is_exactly_these_bytes(self):
        self.assertEqual(site.build_status_js(site.CLEAN).encode("utf-8"),
                         CLEAN_BYTES)

    def test_the_clean_status_holds_a_level_and_nothing_else(self):
        self.assertEqual(dict(site.CLEAN), {"level": "ok"})

    def test_nothing_can_add_to_the_clean_status_by_accident(self):
        # A module-level dict that one caller updates in place is every later
        # build's status too. Read-only, so the accident is an error on the spot.
        with self.assertRaises(TypeError):
            site.CLEAN["text"] = "Built 3 cards."


class TestTheStatusFileIsShapedLikeTheOtherGeneratedFiles(unittest.TestCase):
    """The mark first, then one assignment of one JSON object, like picker-data.js.

    The mark is what ``record_failure`` reads before it will overwrite the file,
    so a status written without it would be the one generated file its own failure
    path refused to touch.
    """

    def test_the_first_line_is_the_generated_mark(self):
        text = site.build_status_js({"level": "fail", "text": "x"})
        self.assertEqual(text.split("\n", 1)[0], site.GENERATED_MARK)

    def test_the_rest_is_one_assignment_of_json(self):
        text = site.build_status_js({"level": "fail", "text": "x"})
        found = re.fullmatch(r"window\.BUILD_STATUS = (.*);\n",
                             text.split("\n", 1)[1], re.S)
        self.assertIsNotNone(found, text)
        self.assertEqual(json.loads(found.group(1)), {"level": "fail", "text": "x"})

    def test_a_reason_in_another_alphabet_arrives_as_written(self):
        text = site.build_status_js({"level": "fail", "text": "Łódź"})
        self.assertIn("Łódź", text)
        self.assertNotIn("\\u", text)


class TestEveryFailureKindHasItsOwnSentence(unittest.TestCase):
    """Ten kinds, one dict, and every sentence exactly as the README quotes it.

    The tenth is a withheld build the guard refused: every card was read, and the
    build stopped rather than write a player's name. Measured before: nine kinds,
    and that refusal left the page at ``{"level": "ok"}``. Rejected: saying it with
    ``input``, whose sentence blames the settings or the scorecards for stopping a
    build that read every card.
    """

    SENTENCES = {
        "no-folder": "The last build failed: no scorecard folder was found, so the "
                     "figures below may be out of date.",
        "no-cards": "The last build failed: no scorecards were found, so the "
                    "figures below may be out of date.",
        "input": "The last build failed: a problem in the settings or the "
                 "scorecards stopped it, so the figures below may be out of date.",
        "withheld": "The last build failed: it stopped rather than write a player's "
                    "name into the dashboard, so the figures below may be out of "
                    "date.",
        "not-written": "The last build failed: the dashboard could not be written, "
                       "so the figures below may be out of date.",
        "unopened": "The last build failed: a file or folder it needed could not "
                    "be opened, so the figures below may be out of date.",
        "internal": "The last build failed: an internal error stopped it, so the "
                    "figures below may be out of date.",
        "unfinished": "The last build failed: it did not finish, so the figures "
                      "below may be out of date.",
    }

    def test_there_are_exactly_ten_kinds(self):
        self.assertEqual(sorted(status.FAILURES),
                         sorted([*self.SENTENCES, "none-read", "too-long"]))

    def test_each_kind_without_a_count_says_its_sentence(self):
        for kind, sentence in self.SENTENCES.items():
            with self.subTest(kind=kind):
                self.assertEqual(status.failed(kind), sentence)

    def test_cards_that_would_not_score_are_counted(self):
        self.assertEqual(status.failed("none-read", 3),
                         "The last build failed: none of the 3 scorecards it found "
                         "could be scored, so the figures below may be out of date.")

    def test_one_card_that_would_not_score_is_not_none_of_one(self):
        self.assertEqual(status.failed("none-read", 1),
                         "The last build failed: the one scorecard it found could "
                         "not be scored, so the figures below may be out of date.")

    def test_a_build_that_was_stopped_says_after_how_long(self):
        self.assertEqual(status.failed("too-long", 10),
                         "The last build failed: it ran for more than 10 minutes "
                         "and was stopped, so the figures below may be out of date.")

    def test_a_build_stopped_after_one_minute_is_not_one_minutes(self):
        self.assertEqual(status.failed("too-long", 1),
                         "The last build failed: it ran for more than 1 minute and "
                         "was stopped, so the figures below may be out of date.")

    def test_one_minute_is_not_one_minutes(self):
        self.assertEqual(status.minutes(1), "1 minute")
        self.assertEqual(status.minutes(10), "10 minutes")
        self.assertEqual(status.minutes(0.02), "0.02 minutes")
        self.assertEqual(status.minutes(1.0), "1 minute")

    def test_a_kind_nobody_wrote_a_sentence_for_is_an_error(self):
        with self.assertRaises(KeyError):
            status.failed("disk-on-fire")


class TestAFailedRunNeverCreatesASiteOrAStatusFile(StatusCase):
    """A failure is written over a status file that is there, and nowhere else.

    A run that found no cards and created ``site/`` to say so would leave a club
    who had never built anything a folder with one file in it and no dashboard,
    and a published folder holding a sentence about a build nobody could see.
    """

    def test_no_out_folder_stays_no_out_folder(self):
        self.assertFalse(status.record_failure(self.out, "no-cards"))
        self.assertFalse(self.out.exists())

    def test_an_out_folder_without_the_file_stays_without_it(self):
        self.out.mkdir()
        self.assertFalse(status.record_failure(self.out, "no-cards"))
        self.assertEqual(list(self.out.iterdir()), [])

    def test_an_empty_file_is_not_one_of_ours(self):
        path = self.seed(b"")
        self.assertFalse(status.record_failure(self.out, "no-cards"))
        self.assertEqual(path.read_bytes(), b"")


class TestAStatusFileThatIsNotOursIsNeverOverwritten(StatusCase):
    """The generated mark is the only evidence the file is this program's (4.6)."""

    def test_a_hand_written_file_is_left_byte_for_byte(self):
        mine = b"window.BUILD_STATUS = {level: 'ok'}; // the club's own\n"
        path = self.seed(mine)
        self.assertFalse(status.record_failure(self.out, "no-cards"))
        self.assertEqual(path.read_bytes(), mine)

    def test_a_file_of_ours_is_overwritten_with_the_sentence(self):
        path = self.seed()
        self.assertTrue(status.record_failure(self.out, "no-cards"))
        self.assertEqual(self.text(path), status.failed("no-cards"))


class TestAStatusFileThatIsALinkIsNeverWrittenThrough(StatusCase):
    """A link at the status file is somebody's, whatever it points at.

    The mark is read through the link, so a link to another project's status
    file passed as this one's. Measured before
    (/tmp/t7/scratch/SITE-A/p63-before.txt): project B's ``build-status.js``
    linked to project A's, and B's run with no cards exited 1 and wrote its
    failure into A's (md5 c278a386 to d600fdf8), the file A's front page loads.
    Rejected: reading the mark at the link's end and writing there if it
    carries one, which is exactly that.
    """

    def test_a_link_to_a_status_file_of_ours_elsewhere_is_left_alone(self):
        elsewhere = self.base / "another" / site.STATUS_FILE
        elsewhere.parent.mkdir()
        elsewhere.write_bytes(CLEAN_BYTES)
        self.out.mkdir()
        (self.out / site.STATUS_FILE).symlink_to(elsewhere)
        self.assertFalse(status.record_failure(self.out, "no-cards"))
        self.assertEqual(elsewhere.read_bytes(), CLEAN_BYTES)
        self.assertTrue((self.out / site.STATUS_FILE).is_symlink())


class TestAFailureRepeatedIsWrittenOnce(StatusCase):
    """An unattended job that fails every 15 minutes rewrites nothing after the first.

    Through the same compare-then-write as every other generated file, so a
    publish that syncs ``site/`` does not upload the same sentence 96 times a day.
    """

    def test_the_second_identical_failure_writes_nothing(self):
        path = self.seed()
        self.assertTrue(status.record_failure(self.out, "no-folder"))
        written = path.stat().st_mtime_ns
        self.assertFalse(status.record_failure(self.out, "no-folder"))
        self.assertEqual(path.stat().st_mtime_ns, written)


class TestTheStatusNeverNamesAPath(StatusCase):
    """The page may be published, and a path can carry somebody's user name."""

    def test_no_sentence_carries_the_folder_or_a_separator(self):
        self.out = self.base / "zz-private-folder" / "site"
        self.out.mkdir(parents=True)
        path = self.seed()
        for kind in status.FAILURES:
            with self.subTest(kind=kind):
                self.assertTrue(status.record_failure(self.out, kind, 2))
                said = self.text(path)
                self.assertTrue(said.startswith("The last build failed: "), said)
                for leak in ("zz-private-folder", "/", "\\"):
                    self.assertNotIn(leak, said)


class TestAStatusThatCannotBeWrittenDoesNotRaise(StatusCase):
    """A failure that cannot be recorded must not become a second failure.

    It is called from build.py's own error handlers, where an exception would
    replace the report of what actually went wrong with a traceback about the
    status file.
    """

    def test_a_folder_where_the_file_should_be(self):
        (self.out / site.STATUS_FILE).mkdir(parents=True)
        self.assertFalse(status.record_failure(self.out, "no-cards"))

    @unittest.skipIf(os.name == "nt", "POSIX permissions")
    @unittest.skipIf(hasattr(os, "geteuid") and os.geteuid() == 0,
                     "root writes through permissions")
    def test_a_read_only_status(self):
        path = self.seed()
        path.chmod(0o444)
        self.out.chmod(0o555)
        self.addCleanup(self.out.chmod, 0o755)
        self.assertFalse(status.record_failure(self.out, "no-cards"))
        self.assertEqual(path.read_bytes(), CLEAN_BYTES)


if __name__ == "__main__":
    unittest.main()
