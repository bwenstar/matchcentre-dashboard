"""``python3 build.py`` — the one command a club actually types.

Everything else in this suite tests the project as a library. This tests it as a
program: run in a fresh directory with nothing but PDFs in ``data/``, does it
produce a working dashboard, does it say what it assumed, and does it fail loudly
when it should?

The three things checked hardest are the three that make the difference between a
tool a club trusts and one it quietly stops using:

**It works with no configuration.** A first run must build a dashboard *and* write
a ``config.toml`` filled in from the cards. If a club has to configure something
before seeing anything, most clubs stop there.

**It says which rules it used.** No scorecard records how its competition awards
points, and ``6-3`` looks identical whether the set was played to 6 or to 8. So
every run prints the scoring in force, whether or not anything is wrong. A ladder
computed under the wrong preset is not an error -- it is a plausible, wrong table,
which is worse.

**A card it cannot read is a failure, not a smaller season.** Six cards scored out
of seven found is a wrong ladder that looks right, so the exit status is nonzero
and the file is named.

Every card is generated by :mod:`matchcentre.cardwriter`, so no real scorecard and
no real club's data is needed to run any of this.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from matchcentre import config as config_mod, site                   # noqa: E402
from test_pipeline import (EXPECTED_LADDER, FIXTURES, TEAMS,         # noqa: E402
                           write_season_cards)

BUILD = ROOT / "build.py"
STAMP = "2026-09-10T12:00:00"


class Run:
    """One invocation of ``build.py``, with everything needed to judge it."""

    def __init__(self, code: int, out: str, err: str, cwd: Path):
        self.code, self.out, self.err, self.cwd = code, out, err, cwd

    @property
    def text(self) -> str:
        return self.out + self.err

    def files(self, directory: str) -> list[str]:
        base = self.cwd / directory
        if not base.is_dir():
            return []
        return sorted(p.relative_to(base).as_posix()
                      for p in base.rglob("*") if p.is_file())


class CliCase(unittest.TestCase):
    """A throwaway project directory per test, holding only ``data/``."""

    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.cwd = Path(self._tmp.name)
        write_season_cards(self.cwd / "data")
        self.addCleanup(self._tmp.cleanup)

    def build(self, *argv: str, expect: int | None = 0) -> Run:
        # Run as a subprocess, not by importing main(): the exit status and the
        # printed report are the interface, and both are easy to get right in
        # process and wrong from a shell.
        done = subprocess.run(
            (sys.executable, str(BUILD), "--generated", STAMP, *argv),
            cwd=self.cwd, capture_output=True, text=True, timeout=600)
        run = Run(done.returncode, done.stdout, done.stderr, self.cwd)
        if expect is not None and run.code != expect:
            self.fail(f"build.py {' '.join(argv)} exited {run.code}, "
                      f"expected {expect}:\n{run.text[-3000:]}")
        return run

    def season(self, competition: str | None = None) -> dict:
        """The season document a build wrote, whatever the competition is called."""
        found = sorted((self.cwd / "site").rglob("season.json"))
        self.assertTrue(found, f"no season.json under {self.cwd / 'site'}; "
                               f"the build wrote {self.files_in('site')}")
        if competition:
            found = [p for p in found if competition in p.parts]
        return json.loads(found[0].read_text(encoding="utf-8"))

    def files_in(self, directory: str) -> list[str]:
        base = self.cwd / directory
        if not base.is_dir():
            return []
        return sorted(p.relative_to(base).as_posix()
                      for p in base.rglob("*") if p.is_file())


class TestAFirstRunNeedsNoConfiguration(CliCase):

    def test_it_exits_zero_with_nothing_but_pdfs_in_data(self):
        run = self.build()
        self.assertIn("exit 0", run.text)

    def test_it_writes_a_config_file_it_can_read_back(self):
        self.build()
        written = self.cwd / "config.toml"
        self.assertTrue(written.is_file(), "a first run must leave a config.toml "
                                           "behind, or there is nothing for a "
                                           "club to edit")
        # Loaded rather than merely parsed: a file that round-trips through the
        # real loader is a file the next run will accept.
        cfg = config_mod.load(written)
        self.assertEqual(list(cfg.warnings), [])

    def test_the_second_run_reads_that_config_and_agrees(self):
        # The config a first run writes is derived from these same cards, so
        # reading it back must not move a single position. If it does, the file
        # the tool writes is not one the tool agrees with.
        self.build()
        before = [t["slug"] for t in sorted(self.season()["teams"],
                                            key=lambda t: t["position"])]
        shutil.rmtree(self.cwd / "site")
        second = self.build()
        after = [t["slug"] for t in sorted(self.season()["teams"],
                                           key=lambda t: t["position"])]
        self.assertEqual(after, before)
        self.assertEqual(after, EXPECTED_LADDER)
        self.assertIn("exit 0", second.text)

    def test_the_second_run_no_longer_calls_the_team_list_derived(self):
        # The point of writing the file: what was a guess becomes declared. If
        # the written `teams` line is commented out, this says so.
        self.build()
        self.build()
        declared = self.season()["meta"]["teams_declared"]
        written = (self.cwd / "config.toml").read_text(encoding="utf-8")
        live = any(line.strip().startswith("teams = [")
                   for line in written.splitlines())
        self.assertEqual(declared, live,
                         f"config.toml {'declares' if live else 'comments out'} "
                         f"teams, but the season document says "
                         f"teams_declared={declared}")

    def test_it_does_not_write_a_config_over_one_that_exists(self):
        self.build()
        written = self.cwd / "config.toml"
        edited = written.read_text(encoding="utf-8") + "\n# a club's own note\n"
        written.write_text(edited, encoding="utf-8")
        self.build()
        self.assertEqual(written.read_text(encoding="utf-8"), edited,
                         "a rebuild overwrote the club's edited config.toml")


class TestTheDashboardIsActuallyThere(CliCase):

    def test_every_file_the_page_needs_is_written(self):
        self.build()
        written = set(self.files_in("site"))
        for name in site.GENERATED:
            with self.subTest(asset=name):
                self.assertTrue(any(p.endswith(name) for p in written),
                                f"{name} is missing from site/, so the page "
                                f"cannot render: {sorted(written)}")

    def test_the_data_island_is_javascript_that_assigns_the_global(self):
        # This file exists only because a browser refuses to fetch() a sibling
        # over file://, which is how a club opens the dashboard: by double-click.
        self.build()
        island = next(p for p in (self.cwd / "site").rglob("season-data.js"))
        text = island.read_text(encoding="utf-8")
        self.assertIn("SEASON_DATA", text)
        self.assertIn("=", text)

    def test_the_island_and_the_json_carry_the_same_season(self):
        self.build()
        island = next((self.cwd / "site").rglob("season-data.js"))
        text = island.read_text(encoding="utf-8")
        start, end = text.find("{"), text.rfind("}")
        self.assertNotEqual(start, -1, "season-data.js holds no object literal")
        embedded = json.loads(text[start:end + 1])
        self.assertEqual(embedded["meta"]["competition"],
                         self.season()["meta"]["competition"])
        self.assertEqual([t["slug"] for t in embedded["teams"]],
                         [t["slug"] for t in self.season()["teams"]])

    def test_the_ladder_in_the_written_season_is_the_expected_one(self):
        self.build()
        teams = sorted(self.season()["teams"], key=lambda t: t["position"])
        self.assertEqual([t["slug"] for t in teams], EXPECTED_LADDER)

    def test_the_page_assets_are_copied_not_linked(self):
        # A symlink into the checkout breaks the moment the club copies site/ to
        # a USB stick or a web host, which is the whole point of site/.
        self.build()
        for path in (self.cwd / "site").rglob("*"):
            if path.is_file():
                with self.subTest(asset=path.name):
                    self.assertFalse(path.is_symlink())


