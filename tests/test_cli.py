class TestRebuildingIsDeterministic(CliCase):

    def test_two_builds_of_the_same_cards_are_byte_identical(self):
        # Without this a club cannot tell a real change from a rebuild, and
        # putting site/ in version control produces a diff every single time.
        #
        # Three builds, comparing the second against the third. The first is
        # deliberately left out of the comparison: it is the run with no
        # config.toml to read, and it writes one on its way out, so the run after
        # it legitimately knows more than it did. What that costs is checked
        # directly by the test below; what must never move is a rebuild from
        # input that has settled.
        self.build()
        first = self.rebuild()
        second = self.rebuild()
        self.assertEqual(sorted(first), sorted(second))
        differing = sorted(p for p in first if first[p] != second[p])
        self.assertEqual(differing, [], f"rebuilding changed {differing}")

    def test_the_config_a_first_run_writes_changes_only_what_it_says_it_knows(self):
        # The one build-to-build difference the tool is allowed: names the first
        # run derived from the cards, the second reads as declared, and the
        # season document's `meta` records the change. Nothing a reader looks at
        # may move with it.
        #
        # This exists because something did. `site.py` and `config.py` each held
        # their own default for the site heading, so a first run titled the page
        # "<club> dashboards" while writing "<club> season dashboards" into the
        # config beside it -- and the second build retitled the site, for no
        # reason a club could have discovered.
        first = self.rebuild()
        second = self.rebuild()
        moved = sorted(p for p in first if first[p] != second[p])
        settled = [p for p in moved if Path(p).name not in
                   ("season.json", "season-data.js")]
        self.assertEqual(settled, [], f"writing config.toml also changed "
                                      f"{settled}, which records no provenance "
                                      f"and had no reason to move")
        for name in moved:
            with self.subTest(document=name):
                self.assertEqual(self.without_meta(first[name]),
                                 self.without_meta(second[name]),
                                 f"{name} changed outside meta, so the second "
                                 f"build did more than record where the names "
                                 f"came from")

    def test_a_rebuild_after_adding_cards_does_change_the_ladder(self):
        # The partner of the test above: identical output must come from
        # identical input, not from output that never changes.
        self.build()
        before = [t["slug"] for t in sorted(self.season()["teams"],
                                            key=lambda t: t["position"])]
        self.add_two_deciding_rounds()
        shutil.rmtree(self.cwd / "site")
        self.build()
        after = [t["slug"] for t in sorted(self.season()["teams"],
                                           key=lambda t: t["position"])]
        self.assertEqual(self.season()["meta"]["rounds_played"], 5)
        self.assertEqual(before, EXPECTED_LADDER)
        self.assertEqual(after, ["parkview-wanderers", "hilltop-aces",
                                 "riverside-rockets", "lakeside-spinners"],
                         f"two rounds of 24-0 whitewashes by the bottom two "
                         f"teams left the ladder at {after}")

    def rebuild(self) -> dict[str, bytes]:
        """Every byte of a site built from scratch, over the config as it stands."""
        shutil.rmtree(self.cwd / "site", ignore_errors=True)
        self.build()
        return {p: (self.cwd / "site" / p).read_bytes()
                for p in self.files_in("site")}

    @staticmethod
    def without_meta(document: bytes) -> str:
        """A season document with everything it says about itself stripped out.

        Text, not JSON: the same routine has to cope with ``season-data.js``,
        which is the same object wrapped in an assignment. Cutting from ``meta``
        to the next top-level key is enough, because the writer sorts keys and
        indents by nesting depth, so a two-space key is always top-level.
        """
        text = document.decode("utf-8")
        start = text.find('\n  "meta"')
        if start < 0:
            return text
        end = text.find('\n  "', start + 4)
        return text[:start] + (text[end:] if end > 0 else "")

    def add_two_deciding_rounds(self):
        """Rounds four and five, in which the bottom two teams win everything.

        Two rounds and not one, because the ladder is ordered by points per
        match and one round cannot span the gap. Under ``games-bonus`` a 24-0
        win pays 4 + 2.4 and the 0-24 loss still pays 2.0, so the most one round
        can swing is 4.4 points -- against a lead of 19.0 to 10.7 spread over
        three matches. Over two rounds the averages land here:

            wanderers  (11.1 + 6.4 + 6.4) / 5 = 4.78    3rd -> 1st
            aces       (10.7 + 6.4 + 6.4) / 5 = 4.70    4th -> 2nd
            rockets    (19.0 + 2.0 + 2.0) / 5 = 4.60    1st -> 3rd
            spinners   (15.8 + 2.0 + 2.0) / 5 = 3.96    2nd -> 4th

        Every position moves, which is what makes a stale build unmistakable
        rather than merely different. Not a mirror image, though: the two winning
        teams keep the 0.4 they started apart, and so do the two losing ones.
        """
        import matchcentre.cardwriter as cw
        from test_pipeline import rows_for
        whitewash = ((6, 0), (6, 0), (6, 0), (6, 0))
        index = 7
        for rnd, date in (("4", "2026-09-08"), ("5", "2026-09-15")):
            folder = self.cwd / "data" / f"Round{rnd}"
            folder.mkdir(parents=True, exist_ok=True)
            for home, away in (("hilltop-aces", "riverside-rockets"),
                               ("parkview-wanderers", "lakeside-spinners")):
                home_name, home_players = TEAMS[home]
                away_name, away_players = TEAMS[away]
                spec = cw.CardSpec(
                    date=date, round_label=rnd, division="B",
                    court=f"{index:02d}", match_id=f"200{index:04d}",
                    home_name=home_name, away_name=away_name,
                    rows=rows_for(whitewash, home_players, away_players),
                    home_roster=tuple(cw.RosterRow(name=n, singles=2.5,
                                                   doubles=2.5, captain=(i == 0))
                                      for i, n in enumerate(home_players)),
                    away_roster=tuple(cw.RosterRow(name=n, singles=2.5,
                                                   doubles=2.5, captain=(i == 0))
                                      for i, n in enumerate(away_players)))
                cw.write_card_file(folder / f"r{rnd}-{index}.pdf", spec)
                index += 1


class TestACardItCannotReadIsAFailure(CliCase):

    def test_a_file_that_is_not_a_pdf_makes_the_run_fail(self):
        # F4. Scoring six of seven cards is a wrong ladder that looks right, so
        # this must not be a warning.
        (self.cwd / "data" / "Round1" / "broken.pdf").write_bytes(
            b"this is not a PDF at all")
        run = self.build(expect=None)
        self.assertNotEqual(run.code, 0, "a card that could not be read left the "
                                         "exit status at 0")

    def test_the_unreadable_card_is_named_so_it_can_be_found(self):
        (self.cwd / "data" / "Round1" / "broken.pdf").write_bytes(b"not a PDF")
        run = self.build(expect=None)
        self.assertIn("broken.pdf", run.text)

    def test_the_cards_that_were_readable_are_still_counted(self):
        # "Everything failed" and "one card failed" need to look different, or
        # the club cannot tell which file to re-export.
        (self.cwd / "data" / "Round1" / "broken.pdf").write_bytes(b"not a PDF")
        run = self.build(expect=None)
        self.assertIn(str(len(FIXTURES)), run.text)

    def test_an_empty_data_directory_fails_rather_than_building_nothing(self):
        # An empty dashboard is the most confusing possible outcome: it looks
        # like the tool ran correctly and the club has no results.
        shutil.rmtree(self.cwd / "data")
        (self.cwd / "data").mkdir()
        run = self.build(expect=None)
        self.assertNotEqual(run.code, 0)
        self.assertIn("data", run.text.lower())

    def test_a_missing_data_directory_says_so_plainly(self):
        shutil.rmtree(self.cwd / "data")
        run = self.build(expect=None)
        self.assertNotEqual(run.code, 0)
        self.assertNotIn("Traceback", run.text,
                         "a missing data/ produced a traceback rather than a "
                         "sentence")


