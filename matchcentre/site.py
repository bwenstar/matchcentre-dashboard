def _sections_html(entries: Sequence[dict], *, multi: bool) -> str:
    """The competition list: grouped by season then day, or by day alone."""
    if not entries:
        return ('    <p class="empty">No scorecards have been read yet. Copy '
                'your exported PDFs into <code>data/</code> and run '
                '<code>python3 build.py</code> again.</p>')
    # Grouped on the season key and day, not on the heading text. Measured on a
    # two-season tree in this session: both seasons' labels came off the cards as
    # "Season 2", so grouping by heading merged them and the picker announced four
    # competitions in one season where two seasons had run two each. The key is the
    # season's identity; the label is only what it is called.
    #
    # Gathered by that identity wherever a card sorts, rather than in runs of cards
    # next to each other, so that :func:`_group` alone decides which cards share a
    # heading: a night spelt ``tuesday.`` is not one the week's order knows and
    # sorts after Wednesday, and a run would give it a heading of its own there. The
    # heading's words are those of the first card the sort puts under it.
    by_ident: dict[tuple[str, str], tuple[str, list[dict]]] = {}
    for entry in entries:
        ident = _group(entry, multi=multi)
        if ident not in by_ident:
            by_ident[ident] = (_heading(entry, multi=multi), [])
        by_ident[ident][1].append(entry)
    groups = [(ident, heading, members)
              for ident, (heading, members) in by_ident.items()]

    # Two groups left showing the same heading would be indistinguishable, so the
    # key that makes them different is shown as well. Only when it happens: a key
    # like "2025-summer" next to a label the club chose is noise the rest of the
    # time.
    repeats = {heading for heading in
               (h for _, h, _ in groups)
               if [h for _, h, _ in groups].count(heading) > 1}

    out: list[str] = []
    for ident, heading, members in groups:
        if heading and heading in repeats and ident[0]:
            heading = f"{heading} ({ident[0]})"
        live = sum(1 for e in members if e["has_results"])
        count = (f'<span class="count">{live} of {len(members)} with results'
                 f'</span>')
        cards = "\n".join(_card_html(e) for e in members)
        head = (f'    <h2>{html.escape(heading)}{count}</h2>\n'
                if heading else f'    <h2>{count}</h2>\n')
        out.append(f'{head}    <div class="picks">\n{cards}\n    </div>')
    return "\n".join(out)


def _heading(entry: dict, *, multi: bool) -> str:
    day = entry["day"]
    if multi:
        season = entry["season_label"] or entry["season_key"]
        return f"{season} - {day}".strip(" -") if (season or day) else ""
    return day


def _card_html(entry: dict) -> str:
    """One competition's card. A link when it has data, inert when it does not."""
    name = html.escape(entry["label"])
    teams = f"{entry['teams']} team{'' if entry['teams'] == 1 else 's'}"

    if not entry["has_data"]:
        # Inert: a div, not an anchor, because there is no dashboard to open and a
        # card that looks like a link is worse than no card at all.
        #
        # What it says is where it came from, not what it is waiting for. "Awaiting
        # scorecards" reads as a promise, and the second way a club sees this card
        # is a division spelt wrongly in the config -- a competition they do not run,
        # which will wait forever. Naming the file names the line to fix.
        source = entry["declared_in"]
        where = f'declared in {html.escape(source)}' if source else 'no results read'
        if entry["declared_as"]:
            # Spelled as every note in the report spells a section, so the words a
            # club reads here are the words to search the report and the file for.
            where += f' as [competitions.{html.escape(entry["declared_as"])}]'
        # The draw's first dated round as the draw gives it: "round 1 on 6 Oct
        # 2026", which is as true the week after as the week before. "Next" is a
        # claim about the reader's today, and a date gone by with no card is not
        # next, it is the night a club finds out the cards were never exported. The
        # year always, and never only when it is not the build's: that is a today
        # too, and would rewrite the page on the first build of a new year.
        first = entry["first_round"]
        when = ([f'round {html.escape(first["number"])} on '
                 f'{html.escape(pretty_date(first["date"], with_year=True))}']
                if first else [])
        # The team count is dropped when there is none to give. A section that says
        # nothing about teams is the common case -- a club types next season's
        # division in before it has the draw -- and "0 teams" reads as a competition
        # with nobody in it rather than as a fact this tool has not been told.
        said = ([teams] if entry["teams"] else []) + when + [where]
        facts = " &middot; ".join(said)
        # The season is written on the card only here. A linked card's season is
        # read off its href, which is unique by construction; an inert card has no
        # href, and without this the page's season buttons would have to show it in
        # every season or none.
        season = (f' data-season="{html.escape(entry["season_key"])}"'
                  if entry["season_key"] else "")
        return (f'      <div class="pick pick-empty"{season}>\n'
                f'        <span class="pick-top"><span class="pick-name">{name}'
                '</span><span class="tag tag-quiet">No results yet</span></span>\n'
                f'        <span class="pick-facts">{facts}</span>\n'
                '      </div>')

    lines: list[str] = []
    played = entry["rounds_played"]
    # A count, "3 of 10 rounds played", as the progress box says it (4.439).
    tag = rounds_played_words(played, entry["rounds_total"]
                              if entry["percent"] is not None else None)
    lines.append(f'        <span class="pick-top">'
                 f'<span class="pick-name">{name}</span>'
                 f'<span class="tag">{html.escape(tag)}</span></span>')
    if entry["percent"] is not None:
        # Only ever drawn against a declared round count. A bar whose denominator
        # was the number of rounds played would read 100% every week (F3).
        lines.append('        <span class="bar" aria-hidden="true">'
                     f'<span style="width:{entry["percent"]}%"></span></span>')

    leader = entry["leader"]
    if entry["placed_first"]:
        # The placings decide 1st where the format is played (4.537).
        lines.append('        <span class="pick-lead"><strong>'
                     f'{html.escape(entry["placed_first"])}</strong> placed 1st'
                     '</span>')
    elif leader:
        # Over once every regular round is in, whatever the counts (4.536).
        verb = "top the final ladder on" if entry["ladder_final"] else "lead on"
        lines.append('        <span class="pick-lead"><strong>'
                     f'{html.escape(str(leader["name"]))}</strong> {verb} '
                     f'{leader["value"]:.2f}</span>')
    elif entry["ladder_state"] == "empty":
        # Not "unequal numbers", which every team on nothing is not (4.428).
        lines.append('        <span class="pick-lead">No regular-season match has '
                     'been counted yet</span>')
    elif entry["cards"]:
        # The document's words for what F10 compared, which are counted matches
        # where a round was credited (4.458); none from an earlier release. Or,
        # on a ladder ordered on the average, its words for the tie at the top
        # that withholds the leader, which the overview's hero gives too: the
        # counts are not why, a division beside it on unequal counts being led
        # (4.523).
        detail = entry["leader_withheld"] or entry["ladder_detail"]
        lines.append('        <span class="pick-lead">Ladder in progress'
                     + (f' &mdash; {html.escape(detail)}' if detail else '')
                     + '</span>')

    facts = f"{teams} &middot; {entry['cards']} card" \
            f"{'' if entry['cards'] == 1 else 's'}"
    if entry["generated"]:
        # Labelled, because a bare date beside "N cards" reads as the night of the
        # last card, and it is neither that nor tonight's run: it is the stamp of
        # the run that last changed this competition's figures
        # (`_dated_as_last_changed`). "generated" because that stamp is the one this
        # competition's own dashboard prints in its header and footer, as
        # "generated". The footer below says "Generated" too, of the newest of these
        # stamps, which is the site's: the latest of the cards' dates, not each
        # card's (4.441).
        facts += (f" &middot; generated "
                  f"{html.escape(pretty_date(entry['generated']))}")
    lines.append(f'        <span class="pick-facts">{facts}</span>')

    if entry["draw_source"] and entry["draw_source"] != "declared":
        lines.append('        <span class="flag">Rounds read from the cards '
                     '&mdash; no draw declared</span>')
    if entry["errors"]:
        lines.append(f'        <span class="flag flag-bad">{entry["errors"]} '
                     f'validation error'
                     f'{"" if entry["errors"] == 1 else "s"}</span>')
    if entry["rejected"]:
        lines.append(f'        <span class="flag flag-bad">{entry["rejected"]} '
                     f'card{"" if entry["rejected"] == 1 else "s"} could not be '
                     f'read</span>')
    if entry["unlisted"]:
        lines.append(f'        <span class="flag flag-bad">{entry["unlisted"]} '
                     f'folder{"" if entry["unlisted"] == 1 else "s"} could not be '
                     f'opened</span>')

    body = "\n".join(lines)
    return (f'      <a class="pick" href="{html.escape(entry["href"])}">\n'
            f'{body}\n      </a>')


def _footer_html(generated: str) -> str:
    """The front page's footer, naming the build that wrote it.

    The version is on both this page and each competition's page rather than only
    on one, because a club that emails a single competition folder has sent the
    dashboard without this page attached.
    """
    foot = (f"Generated by <code>build.py</code> {html.escape(__version__)} "
            f"from the club's own scorecards")
    if generated:
        foot += f" &middot; {html.escape(pretty_date(generated, with_time=True))}"
    return foot


def _picker_data_js(entries: Sequence[dict], *, club: Club, config: Config,
                    generated: str) -> str:
    """The picker's data island, for a template that renders client-side.

    Same records the server-rendered HTML is built from, so the two cannot drift.

    Indented, and an object literal, where ``season-data.js`` is neither: this file is
    945 bytes for one competition and a few kilobytes for a club with a dozen, so the
    parse a ``JSON.parse`` would save is smaller than the measurement error -- and it
    is the file somebody opens when the front page lists the wrong competitions. The
    treatment ``_season_data_js`` gets is worth 3.3ms on a 212KB season and nothing
    here, so it is not applied here.
    """
    payload = {
        "title": _title(club, config),
        "subtitle": _subtitle(entries, config),
        "seasons_mode": config.seasons_mode,
        "theme_key": _theme_key(club, config),
        "generated": generated,
        "competitions": list(entries),
    }
    body = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False,
                      allow_nan=False)
    return (f"{GENERATED_MARK}\n"
            f"window.PICKER_DATA = {body};\n")


def build_status_js(obj: Mapping[str, str]) -> str:
    """``build-status.js``: the mark, then the status as one object literal.

    The only place the file's bytes are made, for the clean build here and for the
    failure status.py writes, so the two cannot come out shaped differently. Built
    like :func:`_picker_data_js`, and copied into a dict first because ``json``
    will not write a read-only mapping.
    """
    body = json.dumps(dict(obj), indent=2, sort_keys=True, ensure_ascii=False,
                      allow_nan=False)
    return f"{GENERATED_MARK}\nwindow.BUILD_STATUS = {body};\n"


def pretty_date(stamp: str, *, with_time: bool = False,
                with_year: bool = False) -> str:
    """``2026-09-08T16:54:07`` -> ``8 Sep``, ``8 Sep, 4:54pm``, or ``8 Sep 2026``.

    Hand-rolled rather than ``strftime``: ``%-d`` is a glibc extension, and
    ``%d`` prints "08 Sep", which reads like a machine wrote it.

    The year is for a date a club typed, which can be any year, rather than one
    this program stamped, which is the season's: without it a draw left over from
    last season read as a fortnight ahead.
    """
    try:
        when = datetime.fromisoformat(stamp)
    except ValueError:
        return stamp
    out = f"{when.day} {when:%b}"
    if with_year:
        out += f" {when.year}"
    if with_time:
        hour = when.hour % 12 or 12
        out += f", {hour}:{when:%M}{'pm' if when.hour >= 12 else 'am'}"
    return out
