class SiteError(Exception):
    """The site cannot be written. Always names the file at fault."""


class CareersSplit(NamedTuple):
    """Why a build's careers page is an index and a page for each initial.

    ``size`` is what the careers would come to as one page's body, in bytes.
    ``kept`` says the page is split although that fits: an earlier build split
    it, and the pages it wrote are kept up to date rather than left behind.
    ``over`` is each page of the split whose own body is past the limit still,
    as (file name, bytes), the largest first: nothing, until a club has a few
    thousand careers and the largest initial's page comes to more than the limit.
    """

    size: int
    kept: bool
    over: tuple[tuple[str, int], ...] = ()


class CareersSummary(NamedTuple):
    """What the report's careers line says: who the careers count, and any split."""

    counts: careers.Counts
    split: CareersSplit | None


class SiteWrite(NamedTuple):
    """What a write did: the files it owns, the ones it wrote, and the date on them.

    Two lists rather than one, because a run that rewrote every file and a run that
    found all of them already right produce the same tree and are not the same
    news. The caller reports the difference, and cannot report it from a single
    list of paths -- which is what this used to be, and is why every run said it
    wrote eight files on a night nothing had been played.

    ``stamp`` is the date the tree now claims for itself, so the report can say
    which build the figures on the page come from without re-deriving it from the
    documents and getting a different answer. ``careers`` is what the careers
    pages it wrote count and how they are split, for the same reason, and
    ``None`` when it wrote none.
    """

    paths: tuple[Path, ...]
    written: tuple[Path, ...]
    stamp: str
    careers: CareersSummary | None = None


class _Writing:
    """One directory being written: what it will hold, and what had to be written.

    A class rather than the same four lines in :func:`write_competition` and in
    :func:`_write_picker`, which is where they started. The counts those two produce
    are added together and reported as one line, so a difference between them --
    one counting a file it skipped, the other not -- would come out as a number no
    reader could question and nothing could contradict.

    The directory is made by the caller, before the stranger check that decides
    whether anything may be written into it at all, so nothing here creates one.
    """

    def __init__(self, out: Path) -> None:
        self.out = out
        self.paths: list[Path] = []
        self.written: list[Path] = []

    def put(self, name: str, data: bytes) -> None:
        """Hold *name* as one of this directory's files, writing it if it has moved."""
        path = self.out / name
        self.paths.append(path)
        if _put(path, data):
            self.written.append(path)

    def done(self, stamp: str) -> SiteWrite:
        return SiteWrite(tuple(self.paths), tuple(self.written), stamp)


def _put(path: Path, data: bytes) -> bool:
    """Write *data* to *path* unless the file there already holds exactly it.

    Returns whether it wrote, which is the whole point: the caller counts.

    Bytes rather than text, and one comparison for templates, documents and pages
    alike, because "the same file" has to mean the same thing for all of them. A
    second copy of this rule, or a shortcut that compared a length or a timestamp,
    is how a file that differs comes to be left alone -- and a dashboard holding
    last week's ladder looks exactly like one holding this week's.

    Any ``OSError`` from the read is treated as "nothing usable is there" and the
    write goes ahead: a missing file is the ordinary case, and for a name taken by
    a directory or a file that cannot be read, the write raises the error the
    caller already reports -- with the ``errno`` in it -- rather than this line
    guessing at which of those it was.

    Written whole or not at all: to ``.<name>.tmp`` beside it, then renamed over
    it, so a write the disk stops leaves the last build's file and not the start
    of this one's. The name is a dotfile, which :func:`_stranger_names` passes
    over, and one per file, so the one a killed run leaves is cleared by the next
    write of that file, and a link at it is removed, never written through. The
    file keeps its mode, and an error in the write or the rename names *path*,
    not the temporary, with the ``errno`` it had; one from clearing the
    temporary's name names that, because what is in the way is there. Never
    asked of a link: written in place it rewrote the file at the other end, and
    renamed over it would put a file where somebody's link was, so links are
    refused before the first write. ``tools/fetch.py`` and ``tools/scheduled.py``
    rename into place too and keep their own: a download never overwrites and is
    synced, because it cannot be rebuilt, and the schedule's record is not under
    ``--out``.
    """
    try:
        if path.read_bytes() == data:
            return False
    except OSError:
        pass
    spare = path.with_name(f".{path.name}.tmp")
    if os.path.lexists(spare):
        spare.unlink(missing_ok=True)
    try:
        with open(spare, "xb") as handle:
            handle.write(data)
        with contextlib.suppress(OSError):
            shutil.copymode(path, spare)
        os.replace(spare, path)
    except OSError as exc:
        raise OSError(exc.errno, exc.strerror, str(path)) from exc
    finally:
        with contextlib.suppress(OSError):
            spare.unlink(missing_ok=True)
    return True


