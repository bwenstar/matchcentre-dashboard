def write_competition(out_dir: str | Path, season: dict, *,
                      single_file: bool = False) -> SiteWrite:
    """Write one self-contained competition directory.

    Returns every path the directory consists of and the ones this call had to
    write, so the caller can report what it did without walking the tree back off
    disk -- and without claiming to have written a file it left alone.

    *single_file* adds the folded one-file copy of the dashboard. It is not the only
    thing that does: a directory that already holds one gets it rewritten whether or
    not the flag came this time, because the run that forgets the flag is the
    unattended one on the night a card landed.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    writing = _Writing(out)

    folded = single_file_name(out)
    fold = single_file or _is_one_file(out / folded)
    if fold and folded in GENERATED:
        # A competition whose id is `index` asks for `index.html`, which is the
        # dashboard's own page. Refused rather than resolved, because either answer
        # is wrong: overwrite the page and the folder has no dashboard in it, skip
        # the fold and the run offers a club a file to send that is not there.
        # Refused here, before anything is written, for the reason `write_site`
        # checks the whole tree up front.
        raise SiteError(
            f"{out} would need its one-file dashboard called {folded}, which is "
            f"already one of this tool's own files ({in_words(GENERATED)}); the "
            f"file is named after the directory, so rename the competition or "
            f"build without --single-file")

    depth = _root_depth(season)
    page = []
    for name in PAGE_ASSETS:
        source = WEB / name
        if not source.is_file():
            raise SiteError(
                f"missing page template {source}: it is copied into every "
                f"competition directory and the dashboard cannot open without it")
        if name == "index.html" and depth != 1:
            page.append((name, _pointed_home(source, depth).encode("utf-8")))
        else:
            page.append((name, source.read_bytes()))

    # Every file made before the first is written, so a shell the home link or
    # the fold cannot use stops the run with the directory as it was. Then the
    # data before the page, so a stop between them never leaves a new page
    # beside the last build's data; the one-file page with the data, since it
    # holds the season too; and season.json last, because the next run measures
    # from it: a season.json this run wrote means the whole dashboard is this
    # run's, which is what build.py reads back after a write that failed.
    files = [("season-data.js", _season_data_js(season).encode("utf-8"))]
    if fold:
        files.append((folded, _folded_page(season)))
    files.extend(page)
    files.append(("season.json", export.season_json(season).encode("utf-8")))
    for name, data in files:
        writing.put(name, data)
    return writing.done(str(season.get("meta", {}).get("generated", "")))


def _root_depth(season: dict) -> int:
    """How many levels up the front page sits from this competition's directory.

    One in single-season mode (``site/<competition>/``) and two in multi-season
    mode (``site/<season>/<competition>/``), which is the same nesting
    :func:`_competition_dir` lays out, read from the same two fields.
    """
    meta = season.get("meta", {}) if isinstance(season, dict) else {}
    multi = meta.get("seasons_mode") == "multi" and meta.get("season_key")
    return 2 if multi else 1


def _pointed_home(source: Path, depth: int) -> str:
    """``index.html``, with its home link aimed *depth* levels up at the picker.

    A template that no longer carries the link verbatim stops the run rather than
    shipping a page whose only route home is a folder listing.
    """
    page = source.read_text(encoding="utf-8")
    if page.count(HOME_LINK) != 1:
        raise SiteError(
            f"{source} does not contain exactly one {HOME_LINK!r}: it is the "
            f"link back to the front page, and a competition nested {depth} "
            f"levels down needs it rewritten before the page will work")
    return page.replace(HOME_LINK,
                        f'class="home-link" href="{"../" * depth}index.html"')


def _js_string_literal(text: str) -> str:
    """``text`` as a double-quoted JavaScript string literal.

    ``json.dumps`` of a string already is one: JSON's string escapes are a subset of
    JavaScript's, so the quotes, the backslashes and the control characters come back
    in a form both languages read the same way. The exceptions are the two line
    separators, which JSON leaves raw and which a JavaScript string literal could not
    hold until ES2019 relaxed it -- a raw one is a syntax error on an older engine, and
    the symptom is a blank dashboard rather than a warning. They reach the document by
    way of ``config.toml``, where a club types the names, and a paste out of a word
    processor carries them.

    Double-quoted and not single-quoted on purpose. A single-quoted literal would cost
    two bytes rather than 32KB, since the document's own double quotes would need no
    escaping -- but then every escape is written here by hand and the inverse is written
    by hand in whatever reads it back, and a mistake mirrored in the pair is the one a
    round trip cannot see. This way the escaping is the standard library's and the
    inverse is ``json.loads``. Measured over 21 loads of headless Chrome, the two shapes
    parse in 6.80ms and 7.20ms, and the 32KB is 376 bytes once gzipped.

    ``<`` goes out as ``\\u003c``, which JSON reads back as ``<`` and which cannot be
    mistaken for markup. Inside a ``<script>`` element a browser ends the script at
    the first ``</script``, wherever in the text it came from -- and this literal
    carries a club's own typing: a team name pasted out of a web page, a captain
    entered with a tag around it, a division a club spelled with a less-than sign.
    The symptom is not a wrong figure but half of ``app.js`` rendered as body text
    on a page with no ladder on it. Escaped here rather than where the page is
    folded, because every copy of the document that reaches a ``<script>`` -- the
    island beside the dashboard, the folded one-file page, the picker's own data --
    comes through this function, and an escape applied at one of the three call
    sites is an escape missing from the other two.
    """
    return (json.dumps(text, ensure_ascii=False)
            .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
            .replace("<", "\\u003c"))


def _season_data_js(season: dict) -> str:
    """``season.json`` wrapped as a script.

    The reason it exists, kept where the next reader will find it: a browser
    refuses to ``fetch()`` a sibling file over ``file://``, so a dashboard opened
    by double-clicking ``index.html`` -- which is how a club opens it -- can only
    receive its data through a ``<script>`` tag.

    Written compact, where ``season.json`` beside it is indented. Nobody reads this
    file: it is generated, it says so, and the browser it is written for cannot see
    the layout. The indentation was 44% of its bytes -- 183KB of the 415KB an
    eight-team home-and-away season came to -- downloaded and parsed on every load.
    The copy to open, diff and read is ``season.json``, which keeps its indentation
    and holds the same document, sorted the same way, so the two can still be
    compared by parsing either.

    Handed to ``JSON.parse`` rather than written as an object literal. An object
    literal is built by the *JavaScript* parser, which weighs at every brace whether
    it has an object, a block, a function body or a destructuring pattern; a string
    is read by a parser with none of that grammar to consider. Measured over nine
    loads of headless Chrome on a real eight-team season's island, inlined so the
    fetch is not in the number: 10.10ms as a literal against 6.80ms parsed, and
    18.20ms against 14.00ms on four times the matches. It costs 32,718 bytes on
    212,174 -- a backslash for each of the document's 32,716 double quotes -- and 376
    bytes of that survives gzip, so it is a disk cost and not a wire cost.
    """
    body = json.dumps(season, separators=(",", ":"), sort_keys=True,
                      ensure_ascii=False, allow_nan=False)
    return (f"{GENERATED_MARK}\n"
            "// A copy of season.json as a script, because a browser will not\n"
            "// fetch() a sibling file over file:// and this page has to open by\n"
            "// double-click. Written on one line on purpose: season.json is the\n"
            "// copy to read, and the indentation this one dropped was 44% of it.\n"
            "// Handed to JSON.parse and not written as an object literal: the JSON\n"
            "// parser reads the same season in 6.8ms where the JavaScript parser\n"
            "// takes 10.1ms, having no expression grammar to weigh at every brace.\n"
            f"window.SEASON_DATA = JSON.parse({_js_string_literal(body)});\n")


# --- the whole dashboard in one file ----------------------------------------
#
# A competition directory is five files -- 520,261 bytes of them on the demo season
# -- and the one anybody would think to send is `index.html`, which on its own is an
# unstyled shell. Measured in headless Chrome as `document.body.innerText` with runs
# of whitespace collapsed: detached into a directory of its own, it renders 166
# characters, and all 166 are `Skip to content`, a link to a front page that is not
# there, the tab labels, the search box, `Theme: system`, and `Loading season...`
# where the competition's name goes. Nothing on it is wrong, because nothing on it is
# anything. The folded page, measured the same way, renders 4,683. The alternatives a
# club is left with are a zip of five files, which a phone will not open, or a web
# server, which is the thing this project exists not to need.
#
# So `--single-file` writes one more file per competition: the same page with the
# stylesheet, the script and the season folded into it, named after the directory
# it sits in. Not written by default -- 358KB per competition per run, published to
# Pages and synced by everything watching `site/`, is a cost a club that never
# sends anybody a ladder should not pay -- but kept current once it exists whether
# or not the flag comes again, because the run that forgets the flag is the
# unattended one on the night a card landed, and a folded page holding last week's
# ladder is indistinguishable from one holding this week's.

# The two anchors that are not a fixed string, as pattern sources rather than
# compiled patterns: all six are combined into one alternation and matched in a
# single pass, so nothing this fold inserts is ever scanned for another anchor.
# That is not tidiness. 205KB of script and 45KB of stylesheet go into this page,
# and a second pass over the result would let a line in one of them stand in for
# the template line it looks like.
#
# The home link, whole, so the fold can take the element out rather than aim it
# somewhere. Anchored on HOME_LINK, the same spelling `_pointed_home` rewrites, so
# the two cannot disagree about what the link looks like.
_HOME_ANCHOR = r"[ \t]*<a " + re.escape(HOME_LINK) + r">.*?</a>\n?"

# The two sentences of the no-script note that name files beside the page. Matched
# across whitespace rather than quoted verbatim, because the template is
# hand-wrapped and a reflow is not a change of meaning; matched from the first
# words to the last, so the wording cannot come out half replaced.
_NOSCRIPT_TEXT = r"This\s+dashboard\s+builds\s+the\s+season\b.*?without\s+it\."

_NOSCRIPT_FOLDED = ("This page builds the season in the browser from the data "
                    "folded into it, so it needs JavaScript enabled. Nothing is "
                    "missing from the folder it came out of: the whole dashboard, "
                    "the season included, is this one file.")


def single_file_name(directory: Path | str) -> str:
    """What a one-file dashboard written into *directory* is called.

    The directory's own name, because the name is the only part of a dashboard that
    survives being attached to an email -- ``index.html`` in a downloads folder is
    every page anybody has ever saved -- and in multi-season mode the competition id
    already carries the season key, so two seasons of one division do not arrive
    under one name.

    Public because build.py reports the file and the stranger check has to recognise
    it. A caller that spelled the name for itself would be a second answer to what a
    folded page is called, and the two would part company as a build that refused
    the file it had written itself.
    """
    return f"{Path(directory).name}.html"


def folded_pages(paths: Iterable[Path]) -> list[Path]:
    """The one-file dashboards among *paths*, by the rule that names them.

    Filtered out of what a write returned rather than worked out again from the
    seasons, so that the files the report offers a club to send are files this run
    answered for.

    The name alone is not the rule. ``--out index`` gives a fold's name,
    ``index.html``, to the front page at the root, and ``--out careers`` gives it
    to the careers page; neither is a dashboard. A fold is the page named after its
    directory with that directory's season document written beside it, which only
    a competition directory has.
    """
    paths = list(paths)
    given = set(paths)
    return [path for path in paths if path.name == single_file_name(path.parent)
            and path.parent / "season-data.js" in given]


def _is_one_file(path: Path) -> bool:
    """Whether *path* is a folded dashboard this tool wrote.

    The mark and not the name, for the reason :data:`SINGLE_FILE_MARK` exists: the
    name is a name a club could have chosen too, and this answer decides both what a
    build may overwrite and what ``--prune`` may delete.

    Only the head of the file is read. A folded page is a whole dashboard -- 358KB
    on the demo season -- and this is asked once per directory under ``--out`` on
    every build. A window rather than the exact offset the mark is written at, so that an
    attribute added to ``<html>``, or a doctype spelled with a space in it, cannot
    turn a page this tool wrote into a stranger that stops the build.
    """
    mark = SINGLE_FILE_MARK.encode("utf-8")
    try:
        with open(path, "rb") as handle:
            return mark in handle.read(512)
    except OSError:
        return False


def _inlinable(text: str, *, tag: str, source: Path) -> str:
    """*text*, refused if it holds a sequence that ends a ``<tag>`` element early.

    A guard on this project's own shipped files, which is the only place either
    sequence could come from: the season document reaches a script through
    :func:`_js_string_literal`, which escapes every ``<`` it contains.

    ``</script`` and ``</style`` end their element wherever they appear, comment or
    string literal included. ``<!--`` is the subtler one and is worth naming: inside
    a script a browser leaves the state it starts only at ``-->``, so an unclosed
    one swallows the rest of the document as script text -- and Python's own
    ``HTMLParser``, which the tests read the folded page with, does not implement
    that state and would not notice.
    """
    lowered = text.lower()
    for sequence in [f"</{tag}"] + (["<!--"] if tag == "script" else []):
        if sequence in lowered:
            raise SiteError(
                f"{source} contains {sequence!r}, which ends a <{tag}> element "
                f"early once the file is folded into a one-file dashboard; the "
                f"rest of the page would render as body text")
    return text


def _folds(season: dict) -> dict[str, tuple[str, str, str]]:
    """Every part of the fold: what it matches, what goes in, and what it is called.

    A table rather than six statements, because the six share one rule -- exactly one
    place in the template, or the run stops and says which part had nowhere to go --
    and the rule is easier to keep right once than six times.

    The stylesheet and the script are read here, and this is the only place either is
    checked for the sequence that would end its element early.
    """
    styles, app = WEB / "styles.css", WEB / "app.js"
    return {
        "mark": (re.escape(DOCTYPE), f"{DOCTYPE}\n{SINGLE_FILE_MARK}",
                 "the mark that says this tool wrote the file"),
        # Removed, not retargeted. Every spelling of "up one level" from a file that
        # reached a reader on its own is a folder listing at best and a 404 at worst,
        # and `<- All competitions` is a promise the file cannot keep.
        "home": (_HOME_ANCHOR, "",
                 "the way back to a front page it has left behind"),
        # The note a reader with scripting off is handed is the one sentence on the
        # page the script does not draw, so it is the one sentence that has to be
        # true of the file they are actually holding -- and the template's version
        # names two files in "this same folder".
        "note": (_NOSCRIPT_TEXT, _NOSCRIPT_FOLDED,
                 "a note for a reader with no JavaScript"),
        "styles": (re.escape(STYLESHEET_LINK),
                   "<style>\n"
                   + _inlinable(styles.read_text(encoding="utf-8"), tag="style",
                                source=styles)
                   + "</style>",
                   "the stylesheet"),
        "season": (re.escape(SEASON_SCRIPT),
                   "<script>\n"
                   "// The season, and the flag saying this page is all there is.\n"
                   "// Both are read before app.js, which is why they are above it.\n"
                   f"{SINGLE_FILE_FLAG}\n"
                   + _season_data_js(season)
                   + "</script>",
                   "the season"),
        "app": (re.escape(APP_SCRIPT),
                "<script>\n"
                + _inlinable(app.read_text(encoding="utf-8"), tag="script",
                             source=app)
                + "</script>",
                "the dashboard's script"),
    }


def _folded_page(season: dict) -> bytes:
    """``index.html`` with the stylesheet, the script and *season* folded into it.

    Built from the template rather than from the copy this run is about to write
    beside it, because the two differ in the one place that matters: the page in the
    folder has a link back to the front page, and a folded page has no site around
    it to go back to.

    One pass. Every anchor is counted against the template and every replacement
    made in the same substitution, so the 205KB of script and 45KB of stylesheet
    this inserts are never scanned for an anchor of their own -- and the
    replacements go in through a function rather than as strings, because a JSON
    document full of ``\\u003c`` escapes is read by :func:`re.sub` as a page of group
    references, which is a corrupted season and not an error.
    """
    source = WEB / "index.html"
    template = source.read_text(encoding="utf-8")
    folds = _folds(season)
    pattern = re.compile("|".join(f"(?P<{name}>{anchor})"
                                  for name, (anchor, _, _) in folds.items()),
                         re.DOTALL)

    found = dict.fromkeys(folds, 0)
    for match in pattern.finditer(template):
        found[match.lastgroup] += 1
    wrong = [f"{count} place(s) to fold in {folds[name][2]}"
             for name, count in found.items() if count != 1]
    if wrong:
        raise SiteError(
            f"{source} has {'; '.join(wrong)}, and a one-file dashboard needs "
            f"exactly one of each; --single-file writes the whole dashboard into "
            f"this page and there is nowhere to put those parts without them")

    return pattern.sub(lambda match: folds[match.lastgroup][1],
                       template).encode("utf-8")


# --- the whole tree ---------------------------------------------------------


def write_site(out_dir: str | Path, *, seasons: Sequence[dict], club: Club,
               config: Config, generated: str | None = None,
               single_file: bool = False, published: bool = False,
               single_file_for: Callable[[str], bool] | None = None,
               players: str = "names") -> SiteWrite:
    """Write every competition directory plus the picker at the root.

    Both the template check and the stranger-file check happen up front, for the
    whole tree, rather than as each directory is written. A run that got three
    ladders onto disk and then refused the fourth would leave the picker linking
    to a dashboard that is not there.

    *published* says the caller has already passed every document through
    :func:`export.published`, as a build that withholds players' names does
    before it rewrites them. Publishing twice is not the same as once: the second
    resolves the data folder's name as if it were a path, from the folder the
    build was run in.

    ``single_file_for``, given a season key, says whether ``single_file`` adds a
    one-file page to that season's competitions (``build.py --only``). It limits
    only the adding: a one-file page already written anywhere is kept up to date
    as always, because a stale one is a wrong figure in somebody's outbox.

    *players* is how the run prints players, as build.py resolved it. It is
    handed to :func:`careers.writes_careers` and asked nothing else here: the
    documents are already rewritten when names are withheld.
    """
    out = Path(out_dir)
    _require_templates()

    # First, so that everything below -- the dating, the three files that carry a
    # document and the front page -- sees only what may leave this machine.
    if not published:
        seasons = [export.published(season) for season in seasons]
    targets = [(competition_dir(out, season, multi=config.multi_season), season)
               for season in seasons]

    strangers = [complaint for directory, _ in targets
                 for complaint in _strangers_in(directory)]
    strangers.extend(_front_page_refusal(out))
    if careers.writes_careers(config, players):
        strangers.extend(_careers_refusal(out))
    if strangers:
        raise SiteError("\n".join(strangers))

    # Dated here, before anything is written, and the dated documents are what both
    # the dashboards and the front page are built from. Doing it inside
    # `write_competition` would leave the picker listing each competition under the
    # date of the run rather than the date of its figures, and the front page is
    # the page a club looks at first.
    targets = [(directory, _dated_as_last_changed(directory / "season.json", season))
               for directory, season in targets]

    # Rendered before anything is written, for the reason the checks above are: a
    # document the careers page cannot add up must stop the run with the old site
    # whole, not with the dashboards rewritten and the page that sums them stale.
    pages = summary = None
    if careers.writes_careers(config, players):
        pages, summary = _careers_pages(out, [season for _, season in targets],
                                        multi=config.multi_season)

    paths: list[Path] = []
    wrote: list[Path] = []
    for directory, season in targets:
        part = write_competition(
            directory, season,
            single_file=single_file and (
                single_file_for is None
                or single_file_for(season["meta"].get("season_key", ""))))
        paths.extend(part.paths)
        wrote.extend(part.written)
    picker = _write_picker(out, [season for _, season in targets], club=club,
                           config=config, generated=generated, players=players)
    paths.extend(picker.paths)
    wrote.extend(picker.written)
    if pages is not None:
        # Stamped as the front page is, with the newest document's date, so a run
        # with nothing new re-dates neither (4.12).
        part = _write_careers(out, pages, club=club, config=config,
                              stamp=picker.stamp, taken=picker.paths)
        paths.extend(part.paths)
        wrote.extend(part.written)
    return SiteWrite(tuple(paths), tuple(wrote), picker.stamp, summary)


def _dated_as_last_changed(path: Path, season: dict) -> dict:
    """*season*, stamped with the run that last changed it rather than with this one.

    A rebuild of cards nobody has touched produces the same document with a new
    ``meta.generated``, and that one field is enough to make every file carrying
    the document differ. Two costs come with it, and the smaller one is the writing:
    the date printed on the page dates the *run*, so a page headed with tonight's
    date can hold a ladder nothing has moved since August. A club reading it cannot
    tell, and a stale figure that looks fresh is the failure this project exists to
    prevent.

    So the test is byte-for-byte: render the document with the stamp the file on
    disk carries, and if that *is* the file on disk, keep that stamp. Nothing else
    about the two documents can differ, because the comparison is of the whole
    text. Rendering and comparing, rather than comparing the two parsed documents,
    because the one in memory holds tuples where the one off disk holds lists, and
    dict equality would call every document different and quietly turn this off.

    Unreadable, unparsable or absent: the new stamp, because in all three cases
    there is nothing on disk to have been written by an earlier run. A stamp that is
    not a string is the same answer for a different reason -- it can only have been
    edited in by hand, and every later reader of the field, this module's own page
    footer included, treats it as text.
    """
    on_disk, document = _on_disk(path)
    if document is None:
        return season
    meta = document.get("meta")
    kept = meta.get("generated") if isinstance(meta, Mapping) else None
    if not isinstance(kept, str):
        return season
    dated = {**season, "meta": {**season.get("meta", {}), "generated": kept}}
    if export.season_json(dated).encode("utf-8") != on_disk:
        return season
    return dated


def previous_season(out_dir: str | Path, season: dict, *,
                    multi: bool = False) -> dict | None:
    """The document an earlier build left where *season* is about to be written.

    For the one question a rebuild cannot answer from the cards alone: what it is
    about to change. Read through this module because this module owns where a
    competition's document goes -- a caller working the path out for itself would
    be a second answer to that, and the two would part company the first time a
    club turned multi-season mode on.

    ``None`` when there is nothing there or nothing readable, which is a first
    build, a run that died half way through a write, or a file edited by hand into
    something that will not parse.
    """
    path = competition_dir(Path(out_dir), season, multi=multi) / "season.json"
    return _on_disk(path)[1]


def _on_disk(path: Path) -> tuple[bytes, dict | None]:
    """The bytes at *path* and the document they parse to, or ``(b"", None)``.

    One reader for the two questions this module asks of a document an earlier run
    wrote -- what stamp it carries and what it said -- so that a file the stamp rule
    treats as absent cannot be a file the change report reads and reports on.
    """
    try:
        raw = path.read_bytes()
        document = json.loads(raw.decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        return b"", None
    return (raw, document) if isinstance(document, dict) else (b"", None)


def _require_templates() -> None:
    if not WEB.is_dir():
        raise SiteError(f"{WEB} does not exist; it holds the page templates "
                        f"({in_words([*PAGE_ASSETS, PICKER, CAREERS_PAGE])}) "
                        f"that every dashboard is built from")
    missing = [name for name in (*PAGE_ASSETS, PICKER, CAREERS_PAGE)
               if not (WEB / name).is_file()]
    if missing:
        raise SiteError("missing page template(s): "
                        + in_words([str(WEB / name) for name in missing]))


def competition_dir(out: Path | str, season: dict, *, multi: bool) -> Path:
    """``site/<competition-id>/``, or ``site/<season>/<competition-id>/``.

    The competition id already carries the season key in multi mode, so the
    season directory is redundant as an identifier. It is here because a club
    keeping five years of seasons wants to see five folders, not fifty.

    Public because :func:`find_orphans` has to be told which directories this run
    is about to write, and a caller that worked the layout out for itself could
    get it wrong in the one direction that matters: name the wrong folder and a
    live dashboard is reported as abandoned.
    """
    out = Path(out)
    meta = season.get("meta", {})
    comp_id = str(meta.get("competition", ""))
    if not comp_id or not _safe_segment(comp_id):
        raise SiteError(f"season document has an unusable competition id "
                        f"{comp_id!r}; it becomes a directory name")
    if not multi:
        return out / comp_id
    key = str(meta.get("season_key", ""))
    if key and not _safe_segment(key):
        raise SiteError(f"season document has an unusable season key {key!r}; "
                        f"it becomes a directory name")
    return (out / key / comp_id) if key else (out / comp_id)


def _safe_segment(value: str) -> bool:
    """Whether a string may be used as one path segment.

    Ids come from :func:`~matchcentre.competition.competition_id`, which slugs
    them, so this can only fail if something upstream stopped doing that. Checked
    anyway: the failure it would otherwise produce is a write outside ``out_dir``.
    """
    return value not in ("", ".", "..") and not any(c in value for c in "/\\:")


def _strangers_in(out_dir: Path) -> list[str]:
    """Complaints about files in a competition directory this tool did not write.

    A generated directory is cheap to rebuild; a page someone hand-edited in it
    is not. Note the asymmetry: the five files in :data:`GENERATED` *are*
    overwritten without asking, because they are this tool's own output, unless
    one is a link. Dotfiles are ignored -- an editor's swap file or a
    ``.DS_Store`` is not a reason to refuse to build a season.
    """
    if not out_dir.exists():
        return []
    if not out_dir.is_dir():
        return [f"{out_dir} is a file; the dashboard needs that name for a "
                f"directory"]
    links, others = _links_and_others(out_dir, _stranger_names(out_dir))
    complaints = [_link_refusal(out_dir / name, "the dashboard")
                  for name in links]
    if others:
        complaints.append(f"{out_dir} holds file(s) this tool did not write "
                          f"({in_words(others)}); move them aside or build "
                          f"into a different --out directory")
    return complaints


def _stranger_names(directory: Path) -> list[str]:
    """Names in *directory* that are not this tool's own output.

    Factored out because two callers need the same answer to two different
    questions -- whether a build may overwrite a directory, and whether
    ``--prune`` may delete one -- and a prune that used a looser rule than the
    build would remove a file the build had refused to touch.

    The one-file dashboard is the one name here that is not decided by the name.
    It is called after the directory, so it is a name a club could have chosen for
    a page of its own about the same division; what makes it ours is the mark
    inside it, which is the same evidence :func:`_is_dashboard` goes on. A page a
    club wrote under that name stays a stranger, and the build says so rather than
    overwriting it.

    A link is a stranger whatever its name, by :func:`_is_link`: the build
    would replace it with a file, and a prune would delete something the club
    made.
    A dotfile is not, which covers the ``.<name>.tmp`` a write stopped between
    its two steps can leave (:func:`_put`).
    """
    folded = single_file_name(directory)
    return sorted(p.name for p in directory.iterdir()
                  if not p.name.startswith(".")
                  and (_is_link(p) or p.name not in GENERATED
                       and not (p.name == folded and _is_one_file(p))))


def _links_and_others(directory: Path, strangers: Sequence[str]
                      ) -> tuple[list[str], list[str]]:
    """*strangers* split: links at the dashboard's own names, and the rest.

    A link at one of the dashboard's own names -- the five in :data:`GENERATED`
    and its one-file page, on every run, as the stranger rule counts them -- is
    named as a link. In the list of files this tool did not write it would read
    as the tool's own file, which by its name it is. A link under any other
    name is a file this tool did not write, as a photo there is. One split for
    the build's refusal and ``--prune``'s, so that a link reads the same in both.
    """
    own = (*GENERATED, single_file_name(directory))
    links = [name for name in strangers
             if name in own and _is_link(directory / name)]
    return links, [name for name in strangers if name not in links]


def _is_link(path: Path) -> bool:
    """Whether *path* is a link, which no file this tool writes ever is.

    Every file a build writes it writes as a file, so a link at one of those
    names is somebody's, whatever it points at -- another project's front page,
    a page outside ``--out`` -- and a write would put a file in its place and
    still exit 0. One rule for the stranger check, the front page's and the
    careers page's refusals, ``--prune`` and the status file a failed build
    rewrites, so that none of them replaces or deletes a link another refused.

    Never asked of a folder a build writes into. ``--out``, a season folder or
    a competition folder may be a link to a folder elsewhere, which is one way
    to publish, and what is written into it is files.
    """
    return path.is_symlink()


def _link_refusal(path: Path, page: str) -> str:
    """The complaint about a link at *path*, a name *page* writes a file at."""
    return (f"{_a_link(path, page)}; move it aside or build into a different "
            f"--out directory")


def _a_link(path: Path, page: str) -> str:
    """What a link at *path* is, in the words of a build's refusal and a prune's.

    A prune says it without the build's advice, because the summary under its
    list gives a prune's.
    """
    return f"{path} is a link, and {page} needs that name for a file of its own"


# --- dashboards nothing builds any more -------------------------------------
#
# A build writes what the cards say and has always been silent about what it did
# not write. That silence is the one way this program can publish a wrong figure:
# delete a division's cards, or switch `seasons` to "multi", and the old
# `site/<competition>/` stays on disk as a complete, openable, correct-looking
# dashboard holding last month's ladder. The picker stops linking it, so nobody
# notices -- and a club that bookmarked it, or emailed the folder, is reading a
# ladder no run will ever update again.
#
# So the build names them. It does not delete them without being asked, because
# `site/` is the club's folder and the run has no way to know a stale dashboard is
# not the one they meant to keep.


@dataclass(frozen=True)
class Orphan:
    """A dashboard directory this tool wrote and this run did not.

    Carries what the stale ``season.json`` still says about itself -- the label,
    the build stamp, the card count -- so the report can describe a competition
    whose cards are gone. That description cannot come from anywhere else: the
    config may no longer mention it and ``data/`` no longer holds it, and "a
    folder called tuesday-division-c" is not enough for a club to decide whether
    to keep it.
    """

    path: Path
    root: Path
    competition: str
    label: str
    generated: str
    cards: int
    mode: str
    duplicate_of: Path | None
    strangers: tuple[str, ...]
    # How the stale copy printed players: "names" unless its document says it
    # withheld them, because every dashboard written before the setting existed
    # printed names, and a copy that printed them is the one a withheld run has to
    # name.
    players: str = "names"
    # "careers" for a careers page this run does not write, which is only ever a
    # run that withholds names; its path is the file, and every field above
    # describes the page rather than a dashboard.
    kind: str = "dashboard"
    # A careers page's files, when it is more than one: the index and the pages
    # a split wrote beside it, every one carrying the mark when it was listed.
    pages: tuple[Path, ...] = ()
    # The stale copy's matches, each its round, its two teams' ids, home first,
    # and the id its card printed (:func:`card_of`), and the season key it was
    # built under: what the report asks of this run's competitions, to say where
    # a card that copy holds was filed this time. Empty when its document lists
    # none or cannot be read, which says nothing either way.
    matches: tuple[tuple[str, str, str, str], ...] = ()
    season_key: str = ""

    @property
    def removable(self) -> bool:
        """Whether ``--prune`` may delete this directory.

        One rule, and the same one the build uses to decide whether it may
        overwrite a directory: everything in it is this tool's own output. A
        prune looser than the build would delete a file the build refused to
        touch.
        """
        return not self.strangers


def find_orphans(out_dir: str | Path, *, keep: Mapping[str, Path],
                 writes_careers: bool = False) -> list[Orphan]:
    """Dashboards under *out_dir* that this run is not writing.

    *keep* maps competition id to the directory this run wrote it to, which is
    both the list to spare and how a duplicate is recognised: the same
    competition found at a path that is not its current one is the mode switch,
    and saying so is more use than saying the folder is stale.

    Every filesystem error is swallowed and the directory dropped. This runs
    *after* a successful build, as a courtesy, and a permission that stops the
    scan must not turn a dashboard a club can open into a traceback. A directory
    that cannot be read is also one that cannot be deleted, so nothing is lost by
    passing over it.

    A careers page is listed too, last, when this run does not write one
    (*writes_careers* false) and the page carries the mark. It is a
    correct-looking page of figures nothing rebuilds. Without the mark it is the
    club's own page and not this tool's to name. Every build printing names
    writes one in either mode, so a change of mode writes over it where it is
    and only a run withholding names lists it.
    """
    out = Path(out_dir)
    # Compared as written, not resolved. Both sides are built by joining onto the
    # same *out_dir* -- these by `iterdir`, those by `competition_dir` -- so there
    # is no second spelling for either to be in.
    live = set(keep.values())
    orphans: list[Orphan] = []
    for path in _dashboards_under(out):
        if path in live:
            continue
        try:
            strangers = tuple(_stranger_names(path))
        except OSError:
            continue
        document = _stale_document(path)
        meta = _meta_of(document)
        comp = str(meta.get("competition", "")) or path.name
        orphans.append(Orphan(
            path=path, root=out, competition=comp,
            label=str(meta.get("label", "")),
            generated=str(meta.get("generated", "")),
            cards=_count(meta.get("cards_scored")),
            mode=str(meta.get("seasons_mode", "")),
            duplicate_of=keep.get(comp),
            strangers=strangers,
            players=players_of(meta),
            matches=_stale_matches(document),
            season_key=str(meta.get("season_key", ""))))
    pages = () if writes_careers else tuple(
        page for page in (out / name for name in (CAREERS_PAGE, *CAREERS_SPLIT))
        if _is_careers_page(page))
    if pages:
        # `players="names"` said rather than defaulted: only a build printing names
        # writes a careers page, so one that carries the mark prints them. One
        # entry however many files a split made of it, under the first of them,
        # named as the mode that wrote it named it. No mode: the page sits at the
        # root in either mode and its reason is about names, so nothing asks
        # which mode wrote it, and a mode read back out of its name would be a
        # mode guessed from words.
        name = _careers_name(pages[0])
        label = name[:1].lower() + name[1:]
        if len(pages) > 1:
            label += f", {len(pages)} pages"
        orphans.append(Orphan(
            path=pages[0], root=out, competition="", label=label,
            generated=_careers_stamp(pages[0]), cards=0, mode="",
            duplicate_of=None, strangers=(), kind="careers", players="names",
            pages=pages))
    return orphans


def players_of(meta: object) -> str:
    """How a dashboard's document says it printed players: ``names`` unless it withheld.

    One rule for the two questions a build asks of what an earlier build left: an
    orphan's, and the one about to be written over. Every document written before
    the setting existed printed names and says nothing, and so does one whose meta
    is not a table at all.
    """
    players = meta.get("players") if isinstance(meta, Mapping) else None
    return str(players) if players else "names"


def remove_orphan(orphan: Orphan) -> list[Path]:
    """Delete one orphaned dashboard, and the season folder it emptied.

    Returns the files removed, so the caller can report a count without having
    walked the tree itself and without trusting :data:`GENERATED` to be what was
    on disk -- a directory written by an older release holds whatever that
    release wrote.

    Raises :class:`SiteError` naming the files at fault when the directory holds
    anything this tool did not write, rather than removing what it can and
    reporting afterwards. A half-deleted dashboard opens, and shows a blank page.

    A careers page is removed only while every file of it still carries the
    mark, and then all of them: each was read when the scan listed it, a page a
    club saved over one since is theirs, and half a split page is an index
    linking pages that are not there.
    """
    if orphan.kind == "careers":
        pages = orphan.pages or (orphan.path,)
        for page in pages:
            if not _is_careers_page(page):
                raise SiteError(f"{page} no longer carries the mark this tool "
                                f"writes into its pages")
        for page in pages:
            page.unlink()
        return list(pages)
    if not orphan.removable:
        # A link at one of the dashboard's own names in the build's words, by
        # the build's split, so the two runs cannot call one link two things.
        # The files first, so the report's line under the path still opens
        # with the words it always had.
        links, others = _links_and_others(orphan.path, orphan.strangers)
        said = [f"{orphan.path} holds file(s) this tool did not write: "
                f"{in_words(others)}"] if others else []
        said.extend(_a_link(orphan.path / name, "the dashboard")
                    for name in links)
        raise SiteError("; ".join(said))
    removed = sorted(p for p in orphan.path.rglob("*") if p.is_file())
    shutil.rmtree(orphan.path)
    _remove_empty_season_dir(orphan)
    return removed


def _dashboards_under(out: Path) -> list[Path]:
    """Every directory under *out* that this tool wrote a dashboard into.

    Two levels deep and no further, because two levels is every layout this
    program produces -- ``site/<competition>/`` and
    ``site/<season>/<competition>/`` -- and an unbounded walk of a directory a
    club chose with ``--out`` is a walk of whatever else is in it. Never descends
    into a dashboard: a competition id and a season key are drawn from the same
    alphabet, so a nested pair would otherwise be reported twice.
    """
    found: list[Path] = []
    for first in _subdirectories(out):
        if _is_dashboard(first):
            found.append(first)
            continue
        found.extend(second for second in _subdirectories(first)
                     if _is_dashboard(second))
    return found


def _subdirectories(directory: Path) -> list[Path]:
    """Sorted child directories, dotfiles skipped, errors swallowed."""
    try:
        return sorted(p for p in directory.iterdir()
                      if p.is_dir() and not p.name.startswith("."))
    except OSError:
        return []


def _is_dashboard(directory: Path) -> bool:
    """Whether this tool wrote the directory, on the evidence in it.

    The test is the first line of ``season-data.js``, and it is deliberately not
    "does this look like a dashboard". A club's own hand-written page in a folder
    named after a division has an ``index.html`` too, and the answer to this
    question decides what ``--prune`` deletes.

    Only the first line is read. The file beside it is a season on one line and
    reaches 400KB, and this runs once per directory under ``--out`` on every
    build.
    """
    return _marked(directory / "season-data.js")


def _marked(path: Path) -> bool:
    """Whether *path* is a file that starts with :data:`GENERATED_MARK`.

    The one reading of the mark, for ``--prune`` deciding a directory is ours and
    for a failed build deciding the status file is. Only the mark's own length is
    read, whatever the file holds after it.
    """
    mark = GENERATED_MARK.encode("utf-8")
    try:
        with open(path, "rb") as handle:
            return handle.read(len(mark)) == mark
    except OSError:
        return False


def _stale_meta(directory: Path) -> dict:
    """What a leftover ``season.json`` says about itself, or nothing.

    Nothing, rather than an exception, for every way it can fail to answer:
    unreadable, truncated by an interrupted write, or written by a release whose
    document was shaped differently. The caller is describing a folder it is
    about to offer to delete, and a missing label is a worse report, not a failed
    one.
    """
    return _meta_of(_stale_document(directory))


def _stale_document(directory: Path) -> dict:
    """A leftover ``season.json`` whole, or nothing, on :func:`_stale_meta`'s terms."""
    try:
        document = json.loads((directory / "season.json")
                              .read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return document if isinstance(document, dict) else {}


def _meta_of(document: dict) -> dict:
    meta = document.get("meta")
    return meta if isinstance(meta, dict) else {}


def _stale_matches(document: dict) -> tuple[tuple[str, str, str, str], ...]:
    """Each match of a leftover document by :func:`card_of`.

    A match that is not a table is four blanks rather than dropped, so that it
    is still counted and matches no card: the report says where a stale copy's
    cards went only when it can say it of every one.
    """
    matches = document.get("matches")
    if not isinstance(matches, list):
        return ()
    return tuple(card_of(m) if isinstance(m, dict) else ("", "", "", "")
                 for m in matches)


def card_of(row: Mapping) -> tuple[str, str, str, str]:
    """A document row's fixture, by :func:`changes.fixture_of`, and the id it printed.

    The id is blank where the card printed none. One reading for a stale copy's
    matches and for this run's, which the report holds side by side to say where
    the cards of a dashboard left behind were filed this run (4.457).
    """
    return (*fixture_of(row), str(row.get("id", "")))


def _count(value: object) -> int:
    """A count out of a stale document, which may hold anything at all."""
    return value if isinstance(value, int) and not isinstance(value, bool) else 0


def _remove_empty_season_dir(orphan: Orphan) -> None:
    """Remove ``site/<season>/`` once the last dashboard in it has gone.

    ``rmdir`` is the whole of the emptiness check, and deliberately: it refuses a
    directory with anything at all in it, including a dotfile and including
    another competition of the same season that this run is still building. One
    syscall, no listing to race against, and no way for this to be the line that
    deletes a live dashboard.

    The season directory is one level up, because ``_dashboards_under`` looks two
    levels deep and no further, so a dashboard's parent is either *root* itself or
    a directory immediately inside it.
    """
    parent = orphan.path.parent
    if parent == orphan.root:
        return
    try:
        parent.rmdir()
    except OSError:
        pass


# --- the picker -------------------------------------------------------------


def _write_picker(out: Path, seasons: Sequence[dict], *, club: Club,
                  config: Config, generated: str | None,
                  players: str = "names") -> SiteWrite:
    """The landing page: every competition the club runs, linked when it has data.

    Listed here is every competition with a dashboard *and* every
    ``[competitions.…]`` section naming a day and a division, whether or not a card
    has ever been filed under it -- because from the outside "this competition has
    no results yet" and "this tool has never heard of it" look identical and only
    one of them is something the reader can wait out. Only the ones with a
    dashboard behind them are links; the rest are inert, and say where they came
    from.
    """
    template = (WEB / PICKER).read_text(encoding="utf-8")
    by_id = {str(s.get("meta", {}).get("competition", "")): s for s in seasons}

    entries = _entries(club, by_id, config=config)
    # The documents first and this run's stamp only as a fallback, which is the
    # opposite of what this line used to do. Every document carries the date its
    # own figures last changed -- see `_dated_as_last_changed` -- so the newest of
    # them is the date the site as a whole last changed, and a front page stamped
    # with the run instead would be the one page claiming figures moved tonight.
    # `generated` still decides the documents, through `export.build_season`, so
    # `--generated` pins this page as firmly as it ever did.
    stamp = (max((s["meta"]["generated"] for s in seasons), default="")
             or generated or "")

    filled = template
    values = {
        "<!--TITLE-->": html.escape(_title(club, config)),
        "<!--SUBTITLE-->": html.escape(_subtitle(entries, config)),
        "<!--COMPETITIONS-->": (_sections_html(entries, multi=config.multi_season)
                                + (_careers_link(config)
                                   if careers.writes_careers(config, players)
                                   else "")),
        "<!--FOOTER-->": _footer_html(stamp),
        "<!--GENERATED-->": html.escape(stamp),
        "<!--THEME-KEY-->": html.escape(_theme_key(club, config)),
    }
    for sentinel in PICKER_SENTINELS:
        filled = filled.replace(sentinel, values[sentinel])

    wants_data = PICKER_DATA in template
    if "<!--COMPETITIONS-->" not in template and not wants_data:
        raise SiteError(
            f"{WEB / PICKER} offers nowhere to put the competition list: it must "
            f"contain the sentinel <!--COMPETITIONS--> or load {PICKER_DATA}. "
            f"Writing it as it stands would produce a picker with no links on it")

    files = _front_page_files(template)
    out.mkdir(parents=True, exist_ok=True)
    writing = _Writing(out)
    writing.put("index.html", filled.encode("utf-8"))

    if PICKER_DATA in files:
        # Only written when the template asks for it, so the tree never carries a
        # file nothing reads.
        writing.put(PICKER_DATA, _picker_data_js(entries, club=club, config=config,
                                                generated=stamp).encode("utf-8"))
    if STATUS_FILE in files:
        # The same rule: only for a template that loads it. The same bytes on every
        # build that got this far, so it is written on a site's first build and on
        # the first good one after a failure, and left alone otherwise.
        writing.put(STATUS_FILE, build_status_js(CLEAN).encode("utf-8"))

    # A self-contained picker.html carries its own CSS, but one that links the
    # dashboard's stylesheet needs a copy beside it: the root is not a
    # competition directory and would otherwise 404.
    for name in PAGE_ASSETS:
        if name != "index.html" and name in files:
            writing.put(name, (WEB / name).read_bytes())
    return writing.done(stamp)


def _careers_link(config: Config) -> str:
    """The front page's link to the careers page, in the words of this mode."""
    return CAREERS_LINK_HTML if config.multi_season else SINGLE_CAREERS_LINK_HTML


def _front_page_files(template: str) -> list[str]:
    """The names the front page is written as: index.html and what it loads.

    Every file *template* names that this tool writes beside it at the root,
    and no other, so the tree never carries a file nothing reads. One list for
    the write and for the refusal of a link at any of them, so a file the front
    page comes to load cannot be written over a link nothing asked about.
    """
    return ["index.html", *(name for name in (PICKER_DATA, STATUS_FILE,
                                             *PAGE_ASSETS)
                            if name != "index.html" and name in template)]


def _front_page_refusal(out: Path) -> list[str]:
    """A complaint for each name the front page is written as that is a link.

    A link and nothing else. The root is the club's folder and the front page
    is this tool's, so a file at one of these names is written over as it
    always was; a link there is somebody's, and a write would put a file in its
    place.
    """
    template = (WEB / PICKER).read_text(encoding="utf-8")
    return [_link_refusal(out / name, "the front page")
            for name in _front_page_files(template) if _is_link(out / name)]


# --- the careers page -------------------------------------------------------


def _careers_pages(out: Path, seasons: Sequence[dict], *, multi: bool = True
                   ) -> tuple[list[tuple[str, str, str]], CareersSummary]:
    """The careers page's file name, heading and body, or every page of its split.

    From the dated documents this run is writing and nothing read off disk, so a
    dashboard left behind under *out* is never added into anybody's career.
    *multi* is the config's mode, which words the page: across seasons, or the
    season's players across its competitions.
    """
    template = (WEB / CAREERS_PAGE).read_text(encoding="utf-8")
    missing = [s for s in CAREERS_SENTINELS if s not in template]
    if missing:
        raise SiteError(f"{WEB / CAREERS_PAGE} is missing {in_words(missing)}; "
                        f"written as it stands the careers page would lose what "
                        f"goes there")
    return _careers_rendered(out, careers_of(seasons), multi=multi)


def careers_summary(out: str | Path, seasons: Sequence[dict], *,
                    multi: bool = True) -> CareersSummary:
    """What the careers in *seasons* count, and whether they go on one page under *out*.

    Asked by the report's careers line only where no write returned it:
    ``--check``, and a write that stopped. Answered by the rendering the site
    write does, so the line says what a build would.
    """
    return _careers_rendered(Path(out), careers_of(seasons), multi=multi)[1]


def _careers_rendered(out: Path, found: Sequence[careers.Career], *,
                      multi: bool = True
                      ) -> tuple[list[tuple[str, str, str]], CareersSummary]:
    """Every careers page's file name, heading and body, what they count, and any split.

    Split whole or not at all: the index and all 28 initials, or the one page.
    Every page of a split is measured as the one page was, so a page of it grown
    past the limit is said, and never taken for one that fits because it is split.
    """
    href = partial(_career_href, out)
    body = careers.body_html(found, href=href, multi=multi)
    split = _split_of(out, body)
    tally = careers.counts(found, multi=multi)
    if split is None:
        return [(CAREERS_PAGE, careers.heading(multi=multi), body)], CareersSummary(
            tally, None)
    pages = [(CAREERS_PAGE, careers.heading(multi=multi),
              careers.index_html(found, page=careers_page_name, index=CAREERS_PAGE,
                                 multi=multi))]
    pages += [(careers_page_name(key), careers.heading(key, multi=multi),
               careers.initial_html(key, found, href=href, page=careers_page_name,
                                    index=CAREERS_PAGE, multi=multi))
              for key in careers.INITIALS]
    over = []
    for name, _, text in pages:
        size = len(text.encode("utf-8"))
        if _past_the_limit(size):
            over.append((name, size))
    over.sort(key=lambda page: -page[1])
    return pages, CareersSummary(tally, split._replace(over=tuple(over)))


def _past_the_limit(size: int) -> bool:
    """Whether a careers page's body of *size* bytes is past :data:`CAREERS_LIMIT`."""
    return size > CAREERS_LIMIT


def _split_of(out: Path, body: str) -> CareersSplit | None:
    """The one rule: past :data:`CAREERS_LIMIT`, or split already, it is split.

    Past the limit as one page's body. Split already when any initial's page
    under *out* carries the mark, so a page that shrinks back under the limit --
    a season taken off the site -- keeps the pages somebody may have saved a link
    to, as a one-file dashboard is kept up to date once it exists, rather than
    leaving them there with old figures on and nothing linking them.
    """
    size = len(body.encode("utf-8"))
    if _past_the_limit(size):
        return CareersSplit(size, kept=False)
    if any(_is_careers_page(out / name) for name in CAREERS_SPLIT):
        return CareersSplit(size, kept=True)
    return None


def careers_of(seasons: Sequence[dict]) -> list[careers.Career]:
    """Every career in *seasons*, and a document the page cannot add up a SiteError.

    Asked by the page and by the report's count, so ``--check`` stops on the
    document a build stops on, with the same sentence.
    """
    try:
        return careers.build(seasons)
    except careers.CareersError as exc:
        raise SiteError(str(exc)) from exc


def _career_href(out: Path, row: careers.SeasonRow, slug: str) -> str:
    """A season row's link: the dashboard its document was written to, by name.

    Worked out by :func:`competition_dir`, the function that decided where that
    dashboard went, so the link and the directory cannot disagree. Asked as of
    multi-season mode in either: a single-season document has no season key,
    which puts it where single-season mode does.
    """
    meta = {"competition": row.competition, "season_key": row.season_key}
    directory = competition_dir(out, {"meta": meta}, multi=True)
    return (directory.relative_to(out).as_posix()
            + "/index.html#/player/" + slug)


def _write_careers(out: Path, pages: Sequence[tuple[str, str, str]], *,
                   club: Club, config: Config, stamp: str,
                   taken: Sequence[Path]) -> SiteWrite:
    template = (WEB / CAREERS_PAGE).read_text(encoding="utf-8")
    out.mkdir(parents=True, exist_ok=True)
    writing = _Writing(out)
    for name, heading, body in pages:
        values = {
            "<!--TITLE-->": html.escape(_title(club, config)),
            "<!--GENERATED-->": html.escape(stamp),
            "<!--THEME-KEY-->": html.escape(_theme_key(club, config)),
            "<!--HEADING-->": html.escape(heading),
            "<!--NAME-->": html.escape(careers.heading(multi=config.multi_season)),
            "<!--CAREERS-->": body,
            "<!--FOOTER-->": _footer_html(stamp),
        }
        filled = template
        for sentinel in CAREERS_SENTINELS:
            filled = filled.replace(sentinel, values[sentinel])
        writing.put(name, filled.encode("utf-8"))
    # The root stylesheet serves the front page too. Listed once however many
    # pages at the root name it, so the report's count is of files.
    if "styles.css" in template and out / "styles.css" not in taken:
        writing.put("styles.css", (WEB / "styles.css").read_bytes())
    return writing.done(stamp)


def _careers_head(path: Path) -> str | None:
    """The start of *path*, where the careers mark and stamp are; None if unread."""
    try:
        with open(path, "rb") as handle:
            return handle.read(_CAREERS_HEAD).decode("utf-8", errors="replace")
    except OSError:
        return None


def _is_careers_page(path: Path) -> bool:
    """Whether *path* is a careers page this tool wrote. The mark, not the name.

    Never a link, whatever it points at. This tool writes the page as a file, so a
    link in its place is somebody's, and writing the page would replace it with a
    file. One rule for the build's refusal, the left-behind scan and
    the prune's second look, so a prune never removes what a build refused to touch.
    """
    if _is_link(path):
        return False
    head = _careers_head(path)
    return head is not None and CAREERS_MARK in head


def _careers_stamp(path: Path) -> str:
    head = _careers_head(path) or ""
    found = re.search(r'<meta name="generated" content="([^"]*)">', head)
    return html.unescape(found.group(1)) if found else ""


def _careers_name(path: Path) -> str:
    """The name a careers page was written under, as its topbar gives it.

    Read back from its head, because the left-behind report names the page as
    the mode that wrote it did and this run's mode may be the other. A page with
    none was written before single-season mode wrote one, so it is the page
    across seasons.
    """
    head = _careers_head(path) or ""
    found = re.search(r'<meta name="page" content="([^"]*)">', head)
    return html.unescape(found.group(1)) if found else careers.HEADING


def _careers_refusal(out: Path) -> list[str]:
    """A complaint for each careers page name a file this tool did not write has.

    Every name a split can need, asked on every build that writes the page, split
    or not. So a club's own ``careers-q.html`` is refused on the night somebody is
    watching, in the one error with the rest, and never first on the unattended
    night the careers grow past the limit.
    """
    complaints = []
    for page in (out / name for name in (CAREERS_PAGE, *CAREERS_SPLIT)):
        if _is_link(page):
            complaints.append(_link_refusal(page, "the careers page"))
            continue
        if not page.exists():
            continue
        if page.is_file() and _is_careers_page(page):
            continue
        complaints.append(f"{page} is not a page this tool wrote, and the careers "
                          f"page needs that name; move it aside or build into a "
                          f"different --out directory")
    return complaints


def _title(club: Club, config: Config) -> str:
    """The site's own heading, from the config, never from this file.

    Asked of :func:`matchcentre.config.site_title` rather than worked out again
    here, so that the heading on a first run, the ``title =`` line that same run
    writes into ``config.toml`` and the title the guard searches cannot disagree.
    """
    return site_title(config, club.name)


def _theme_key(club: Club, config: Config) -> str:
    """A ``localStorage`` key unique to this club's site.

    Derived rather than hardcoded because two clubs' dashboards can end up served
    from one origin -- a shared Pages site, or a folder holding both -- and a
    single fixed key means either one silently overwrites the other's light/dark
    choice. That is a bug nobody reports, because nobody can describe it.
    """
    for candidate in (club.name, config.title):
        if candidate:
            try:
                return f"{slugify(candidate)}-theme"
            except ValueError:
                continue
    return "matchcentre-theme"


def _subtitle(entries: Sequence[dict], config: Config) -> str:
    """One line of arithmetic under the title. Says nothing about seasons in single mode.

    A competition with results is one with a night played (4.440), not one with a
    document: a folder of washouts writes a document and has none.
    """
    live = sum(1 for e in entries if e["has_results"])
    total = len(entries)
    if not total:
        return "No competitions found yet"
    body = f"{live} of {total} competition{'' if total == 1 else 's'} with results"
    if config.multi_season:
        keys = {e["season_key"] for e in entries if e["season_key"]}
        if keys:
            body += f" across {len(keys)} season{'' if len(keys) == 1 else 's'}"
    return body


def _entries(club: Club, by_id: dict[str, dict], *, config: Config) -> list[dict]:
    """One plain-data record per competition, ordered the way the picker shows them.

    Plain dicts rather than objects because these feed both the server-rendered
    HTML and ``picker-data.js``, and the two must not be able to disagree.

    Three sources, unioned on the competition id. The club and the season
    documents are the competitions that were built. The third is the config's own
    sections, which is how a competition that has not been played yet gets onto the
    page at all -- and only those a card could actually be filed under
    (:attr:`~matchcentre.config.CompetitionConfig.can_claim_cards`), because a
    section naming a division and no night matches nothing and listing it would
    mean choosing a night for it.

    Unioning on the id is what keeps one competition to one card. A section's own
    name is the id its cards are given when they arrive, so the entry a club watches
    fills in where it stands; unioning on the *generated* id instead would list the
    same competition twice, once linked and once not.
    """
    known = {comp.id: comp for comp in club.competitions}
    declared = {comp_id: section
                for comp_id, section in config.competitions.items()
                if section.can_claim_cards}
    # A competition with a season document but no entry in the club is a bug
    # upstream rather than a reason to lose a dashboard, so it is listed too.
    ids = sorted(set(known) | set(declared) | set(k for k in by_id if k))
    entries = [_entry(known.get(comp_id), by_id.get(comp_id), comp_id,
                      declared=declared.get(comp_id), config=config)
               for comp_id in ids]
    # Two passes rather than one key, because the season runs newest first and
    # everything under it runs forwards. `list.sort` is stable, so ordering within
    # a season and then by season leaves both right, and neither has to be
    # expressed backwards to fit in the other's tuple -- which is what the
    # character-by-character reversal this replaced was doing.
    entries.sort(key=_entry_sort_key)
    entries.sort(key=lambda entry: season_order_key(entry["season_key"]),
                 reverse=True)
    _name_sections_that_read_alike(entries, multi=config.multi_season)
    return entries


def _entry(comp: Competition | None, season: dict | None, comp_id: str, *,
           config: Config, declared: CompetitionConfig | None = None) -> dict:
    """One record. *declared* is the club's own section, read only where nothing else knows.

    The fallback order is the built competition, then its season document, then the
    section -- so a section that disagrees with the cards never overrides them, and
    a competition nobody has played yet has only the section left to describe it.
    """
    multi = config.multi_season
    meta = (season or {}).get("meta", {})
    played = meta.get("rounds_played", 0)
    total = meta.get("rounds_total")
    if total is None and season is None and declared is not None:
        # The section's length only where there is no document to have one. A
        # document's null is its answer: F3 refused the length the section declares,
        # and read from the section, the tag said "Round 3 of 1" over it.
        total = declared.rounds_total
    label = ((comp.display_label if comp else "") or meta.get("label")
             or _declared_label(declared) or comp_id)
    teams = meta.get("teams_total")
    if teams is None:
        teams = len(comp.teams) if comp else len(declared.teams) if declared else 0
    entry = {
        "id": comp_id,
        "label": label,
        "day": ((comp.day if comp else "") or meta.get("day", "")
                or (declared.day if declared else "")),
        "division": ((comp.division if comp else "") or meta.get("division", "")
                     or (declared.division if declared else "")),
        # Empty for anything with no dashboard behind it. A link this run did not
        # write is a folder listing at best, and the file:// reader it would be
        # shown to has no server to tidy that up.
        "href": _href(comp_id, meta, multi=multi) if season is not None else "",
        "has_data": season is not None,
        # A night played, which the counters count (4.440). Apart from `has_data`,
        # which links the card: a season of washouts has a dashboard, and the
        # washouts are explained there.
        "has_results": bool(meta.get("matches_played")),
        # Where this entry came from, and only when that is the whole story: a
        # competition on the page with no results and no cards has to say why it is
        # there, because the other thing that puts it there is a misspelt division.
        "declared_in": (named(config.path)
                        if declared is not None and season is None else ""),
        # The draw's first dated round, for the same card and only that one: a
        # card with results says how far the season has got, and the date it
        # started is last month's news above this week's figures.
        "first_round": (_first_dated_round(declared)
                        if declared is not None and season is None else None),
        # The section's own name, filled in afterwards and only where two cards
        # under one heading read alike -- see `_name_sections_that_read_alike`.
        "declared_as": "",
        "teams": teams,
        "cards": meta.get("cards_scored", 0),
        "rounds_played": played,
        # Null unless declared (F3). The card shows a bar only when it is not,
        # because "3 rounds played" is a fact and "30%" needs a denominator.
        "rounds_total": total,
        "percent": (min(100, round(100 * played / total))
                    if total else None),
        "ladder_complete": meta.get("ladder_complete", False),
        # Which of F10's three, for the card's line under a ladder with no leader.
        "ladder_state": meta.get("ladder_state"),
        # And the state in words, played or counted, as the report says it (4.458).
        "ladder_detail": meta.get("ladder_detail", ""),
        # Why nobody leads where the counts are not why: a top row level on the
        # average with a team on another count (4.523). Empty from an earlier
        # release, whose card says the state as it did.
        "leader_withheld": meta.get("leader_withheld") or "",
        # Whether the regular season is over (4.536), and who the placings put
        # first once they have (4.537): the card says those in place of a lead.
        "ladder_final": meta.get("ladder_final", False),
        "placed_first": _placed_first(season),
        "draw_source": meta.get("draw_source", ""),
        # The competition's own errors. Its refused cards are `rejected` below,
        # and flagged once as cards that could not be read.
        "errors": len(export.own_findings(
            (season or {}).get("validation", {}).get("errors", ()))),
        "warnings": len((season or {}).get("validation", {}).get("warnings", ())),
        "rejected": meta.get("cards_rejected", 0),
        # And the folders the reader could not list, flagged apart: no card.
        "unlisted": meta.get("folders_unlisted", 0),
        "generated": meta.get("generated", ""),
        "leader": _leader(season),
    }
    # Season fields exist only in multi mode: in single mode the picker must not
    # mention seasons at all, and the surest way to honour that is to give the
    # renderer nothing to mention.
    if multi:
        entry["season_key"] = meta.get("season_key", "") or (
            comp.season_key if comp else "") or (
            declared.season_key if declared else "")
        # Named by the rules a season document is, and asked again of a section no
        # card has reached: its own season, its [seasons] line, then its key.
        entry["season_label"] = meta.get("season_label", "") or export.season_label(
            comp.season if comp else
            discover.season_name(config, declared, entry["season_key"])[0],
            entry["season_key"])
    else:
        entry["season_key"] = ""
        entry["season_label"] = ""
    return entry


def _declared_label(declared: CompetitionConfig | None) -> str:
    """What to call a competition that exists only as a config section.

    The club's ``label`` if they wrote one. Otherwise the day and the division, by
    the same rule :meth:`Competition.display_label` uses on a competition that has
    been played -- so the entry keeps its name when its cards arrive, instead of
    being renamed by the run that finally builds it.

    Never the section's own name. ``[competitions.tuesday-grade-b]`` is an id, and a
    front page reading "tuesday-grade-b" says this tool named it, which is exactly
    backwards: the id is the one part of that section the club is free to make up.
    """
    if declared is None:
        return ""
    if declared.label:
        return declared.label
    parts = [p for p in (declared.day, division_label(declared.division)) if p]
    return " ".join(parts)


def _first_dated_round(declared: CompetitionConfig) -> dict | None:
    """The first round, in the order the season runs, that the draw gives a date for.

    For a card with no dashboard behind it, which is a competition no card has been
    read for. That is why no date is compared with anything here. Whether the season
    has got past a round is answered by other cards and never by the calendar
    (:func:`matchcentre.stats.later_round_with_cards`), and with no card at all the
    answer for every round is that it has not -- so the first round is the one to
    give, whatever day the build is dated. Choosing "the next one" by
    ``--generated`` instead would decide from a date that a round nobody sent a card
    for has been played, which is the question that rule exists to keep away from
    the clock; and it would have a rebuild on a later day rewrite the front page with
    no card changed, under a footer still giving the day its figures last moved.

    In the order the season runs (:func:`~matchcentre.competition.round_sort_key`),
    not the order the file lists them or their order as text, which puts round 10
    before round 2. A round with no date is passed over rather than lent the next
    round's, so a draw whose first night is not fixed yet says ``round 2 on 13 Oct``
    and never ``round 1 on 13 Oct``. And not the earliest date: a round 1 moved
    behind round 2 is still round 1, the first line of the draw as the dashboard
    lists it, and ordering by date would need every date read as one, which
    ``6 & 7 Oct`` is not. Whether a date is blank was settled when the file was
    read, as it is for every other reader of a round's date. The key is handed the
    draw, so a final it types under a name of its own, ``Major Semi``, comes after
    the QF typed above it (4.71).
    """
    draw = {rnd.number: rnd for rnd in declared.rounds}
    for rnd in sorted(declared.rounds, key=lambda r: round_sort_key(r.number, draw)):
        if rnd.date:
            return {"number": rnd.number, "date": rnd.date}
    return None


def _group(entry: dict, *, multi: bool) -> tuple[str, str]:
    """The heading a card is listed under, as an identity rather than as its text.

    One function because two questions are asked of it and must get one answer:
    which cards share a heading, in :func:`_sections_html`, and which cards under one
    heading read alike, in :func:`_name_sections_that_read_alike`.

    The night by :func:`~matchcentre.slugs.label_key`, the rule the config load
    uses when it refuses two sections claiming one night and division. Compared as
    typed, ``day = "Tuesday "`` was measured heading a list of its own beside
    ``Tuesday``'s -- two headings HTML shows alike -- with a card under each that
    read alike and neither named, because each was alone under its heading.
    """
    return (entry["season_key"] if multi else "", label_key(entry["day"]))


def _name_sections_that_read_alike(entries: Sequence[dict], *, multi: bool) -> None:
    """Give a card with no dashboard its section's name when another card reads like it.

    Measured on the README's own worked example -- cards printing ``Division 3
    Grade B`` beside a section that says ``division = "Division 3 Grade B"`` -- the
    front page listed ``Tuesday Division 3 Grade B`` twice under one heading, once
    linked and once greyed, and nothing on the greyed one said which section it
    was. Two sections with no cards do the same: a division written ``C`` and
    ``Division C``, one night under two season keys in single-season mode, two
    labels that differ only in case, punctuation or spacing, and one night spelt
    two ways.

    The section's name is what tells them apart, because it is the one thing two
    sections cannot share, it is what the run's note about a section that matched
    nothing calls it, and it is the line a club has to find. The field the two
    happen to differ in was the rejected alternative: it is a different field each
    time -- the division, how the division was spelt, a season key that
    single-season mode never shows -- and in the worked example it would print the
    misspelling as though it were a division.

    Alike by :func:`~matchcentre.slugs.label_key`, the rule that decides whether two
    labels are one competition when a card is filed and when the config is loaded,
    and under one heading, because the heading is part of what a reader reads. A
    linked card is compared with but never named: it is a link to its results,
    which already tells it apart. And a card whose name is its own says nothing
    more, because a section's name on a public page the rest of the time is the
    configuration file talking to itself.
    """
    def key(entry: dict) -> tuple[tuple[str, str], str]:
        return (_group(entry, multi=multi), label_key(entry["label"]))

    seen = Counter(key(entry) for entry in entries)
    for entry in entries:
        if entry["declared_in"] and seen[key(entry)] > 1:
            entry["declared_as"] = entry["id"]


def _href(comp_id: str, meta: dict, *, multi: bool) -> str:
    """The link from the front page to one competition's dashboard.

    Names ``index.html`` rather than ending at the directory. A web server would
    fill that in; a browser opening the file directly will not, and shows a
    directory listing instead of the dashboard. This tool promises that
    double-clicking works, so the file is named.
    """
    key = meta.get("season_key", "") if multi else ""
    return f"{key}/{comp_id}/index.html" if key else f"{comp_id}/index.html"


def _placed_first(season: dict | None) -> str:
    """The team the placings put 1st, by the name the card prints, or ``""`` (4.537).

    Only once the top placing match has placed somebody: before it, the ladder's
    top row leads, and the card says so.
    """
    placed = (season or {}).get("placings") or {}
    first = next((match["first"] for match in placed.get("matches", ())
                  if match["places"][0] == 1), None)
    if not first:
        return ""
    row = next((t for t in season["teams"] if t["slug"] == first), None)
    return (row["short"] or row["name"]) if row else first


def _leader(season: dict | None) -> dict | None:
    """The team the document names its leader, with the figure it leads on.

    ``meta.leader``, which the build names on a complete ladder, and on one in
    progress ordered on the average unless its top row is level on it with a
    team on another count (4.523). On one in progress ordered on a total the
    top row is a snapshot, so the build names nobody (F10, 4.209), and nor
    does it on a top row level so; on both the picker says the ladder is in
    progress instead of crowning anyone, and why, ``meta.leader_withheld`` on
    the second. Read here and not worked out again, so the front page and the
    overview crown the same team or nobody (4.438).
    """
    leader = (season or {}).get("meta", {}).get("leader")
    if not leader:
        return None
    # A slug the rows do not hold names nobody: no build writes one, and a document
    # a hand wrote is no reason to stop the front page.
    row = next((t for t in season["teams"] if t["slug"] == leader["slug"]), None)
    if row is None:
        return None
    return {"name": row["short"] or row["name"], "value": leader["value"]}


def _entry_sort_key(entry: dict) -> tuple:
    """Inside one season: the week as it runs, then division, then id.

    The season itself is a separate pass, because it sorts the other way round.
    """
    day = entry["day"].strip().casefold()
    day_rank = _DAY_ORDER.index(day) if day in _DAY_ORDER else len(_DAY_ORDER)
    return (day_rank, entry["day"], entry["division"], entry["id"])


